"""Fabric's convention tags for Kiln's data pack (D-201): writes kiln/mixins/kiln/convention_tags.rs from Fabric API's
fabric-convention-tags-v2 jar, the `c` tags of items, blocks, fluids, entity types, enchantments and potions, which
recipes and code of Fabric mods name (`#c:ingots/iron`) and the game's own data doesn't have. Its biome tags are left
out: they place structures, and Horizon's port pack carries the ones a structure names.

    python3 -I tools/convention-tags.py [JAR]

JAR is fabric-convention-tags-v2-<version>.jar; by default the one Gradle downloaded for mods/kiln-testbench (Fabric
API 0.165.0+26.3). The files name only ids (`minecraft:iron_ingot`, `#c:ingots/copper`); a file with anything else
stops the script. They are Fabric API's data, under the Apache License 2.0 (FabricMC), which the generated file says.
"""
import glob
import json
import os
import sys
import zipfile

KINDS = ("item", "block", "fluid", "entity_type", "enchantment", "potion")
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "kiln/mixins/kiln/convention_tags.rs")


def default_jar():
    found = sorted(glob.glob(os.path.expanduser(
        "~/.gradle/caches/modules-2/files-2.1/net.fabricmc.fabric-api/fabric-convention-tags-v2/*/*/*.jar")))
    found = [j for j in found if not j.endswith("-sources.jar")]
    if not found:
        sys.exit("no fabric-convention-tags-v2 jar in Gradle's cache: build mods/kiln-testbench, or name the jar")
    return found[-1]


def only_ids(tag, name):
    """The tag with nothing but its values (and `replace`), each an id or `{"id", "required"}`."""
    if set(tag) - {"values", "replace"}:
        sys.exit(f"{name}: keys {sorted(tag)}")
    for v in tag.get("values", []):
        ok = isinstance(v, str) or (isinstance(v, dict) and set(v) <= {"id", "required"} and isinstance(v.get("id"), str))
        if not ok:
            sys.exit(f"{name}: value {v!r}")
    return tag


def main():
    jar = sys.argv[1] if len(sys.argv) > 1 else default_jar()
    with zipfile.ZipFile(jar) as z:
        meta = json.loads(z.read("fabric.mod.json"))
        if meta.get("license") != "Apache-2.0":
            sys.exit(f"{jar}: licence {meta.get('license')!r}, not Apache-2.0")
        tags = []
        for name in sorted(z.namelist()):
            parts = name.split("/")
            if len(parts) < 5 or parts[:3] != ["data", "c", "tags"] or not name.endswith(".json"):
                continue
            if parts[3] not in KINDS:
                continue
            tag = only_ids(json.loads(z.read(name)), name)
            key = "/".join(parts[3:])[: -len(".json")]
            tags.append((key, json.dumps(tag, separators=(",", ":"))))
    lines = [
        f"// Generated by tools/convention-tags.py from Fabric API's {meta['id']} {meta['version']} (D-201): its `c` tags",
        "// of items, blocks, fluids, entity types, enchantments and potions, as `<kind>/<path>` and the file's JSON. Don't",
        "// edit it: run the script again. The tag files are Fabric API's (Copyright FabricMC, Apache License 2.0,",
        "// https://www.apache.org/licenses/LICENSE-2.0); they name only ids.",
        "",
        "/// The Fabric API module the tags come from.",
        f"pub const SOURCE: &str = \"{meta['id']} {meta['version']}\";",
        "",
        "/// `(<kind>/<path>, JSON)`: `data/c/tags/<kind>/<path>.json` in a data pack.",
        "#[rustfmt::skip]",
        "pub const TAGS: &[(&str, &str)] = &[",
    ]
    for key, text in tags:
        if '"##' in text:
            sys.exit(f"{key}: can't be a raw string")
        lines.append(f"    (\"{key}\", r##\"{text}\"##),")
    lines.append("];")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    by_kind = {k: sum(1 for t, _ in tags if t.startswith(k + "/")) for k in KINDS}
    print(f"{OUT}: {len(tags)} tags from {os.path.basename(jar)} ({', '.join(f'{k} {n}' for k, n in by_kind.items())})")


if __name__ == "__main__":
    main()
