def parse(data):
    """A class file's names, flags, signatures, fields, methods, nested classes and record components."""
    if data[:4] != b"\xca\xfe\xba\xbe":
        raise ValueError("not a class file")
    count = struct.unpack(">H", data[8:10])[0]
    pool = [None] * count
    i, pos = 1, 10
    while i < count:
        tag = data[pos]
        if tag == 1:
            n = struct.unpack(">H", data[pos + 1:pos + 3])[0]
            pool[i] = ("utf8", data[pos + 3:pos + 3 + n].decode("utf-8", "replace"))
            pos += 3 + n
        elif tag == 3:
            pool[i] = ("int", struct.unpack(">i", data[pos + 1:pos + 5])[0])
            pos += 5
        elif tag == 4:
            pool[i] = ("float", struct.unpack(">f", data[pos + 1:pos + 5])[0])
            pos += 5
        elif tag == 5:
            pool[i] = ("long", struct.unpack(">q", data[pos + 1:pos + 9])[0])
            pos += 9
            i += 1
        elif tag == 6:
            pool[i] = ("double", struct.unpack(">d", data[pos + 1:pos + 9])[0])
            pos += 9
            i += 1
        elif tag in (7, 8, 16, 19, 20):
            pool[i] = (tag, struct.unpack(">H", data[pos + 1:pos + 3])[0])
            pos += 3
        elif tag in (9, 10, 11, 12, 17, 18):
            pool[i] = (tag,) + struct.unpack(">HH", data[pos + 1:pos + 5])
            pos += 5
        elif tag == 15:
            pos += 4
        else:
            raise ValueError(f"constant pool tag {tag}")
        i += 1

    def utf8(k):
        return pool[k][1]

    def cls(k):
        return utf8(pool[k][1]) if k else None

    def u2(p):
        return struct.unpack(">H", data[p:p + 2])[0]

    def attributes(p):
        """The attributes at `p` (their count first), by name: (start, length); and where they end."""
        n, p = u2(p), p + 2
        found = {}
        for _ in range(n):
            name, length = utf8(u2(p)), struct.unpack(">I", data[p + 2:p + 6])[0]
            found[name] = (p + 6, length)
            p += 6 + length
        return found, p

    access, this, sup, n = struct.unpack(">HHHH", data[pos:pos + 8])
    pos += 8
    interfaces = [cls(u2(pos + 2 * j)) for j in range(n)]
    pos += 2 * n
    members, ids = [], {}
    for kind in ("field", "method"):
        n = u2(pos)
        pos += 2
        for _ in range(n):
            flags, name, desc = struct.unpack(">HHH", data[pos:pos + 6])
            attrs, pos = attributes(pos + 6)
            if kind == "method" and utf8(name) == "<clinit>" and "Code" in attrs:
                start = attrs["Code"][0]
                length = struct.unpack(">I", data[start + 4:start + 8])[0]
                ids = clinit_ids(data[start + 8:start + 8 + length], pool, cls(this))
            signature = utf8(u2(attrs["Signature"][0])) if "Signature" in attrs else None
            constant = None
            if "ConstantValue" in attrs:
                entry = pool[u2(attrs["ConstantValue"][0])]
                constant = utf8(entry[1]) if entry[0] == 8 else entry[1]
            members.append({"kind": kind, "access": flags, "name": utf8(name), "desc": utf8(desc),
                            "signature": signature, "constant": constant})
    attrs, _ = attributes(pos)
    signature = utf8(u2(attrs["Signature"][0])) if "Signature" in attrs else None
    inner = []
    if "InnerClasses" in attrs:
        p = attrs["InnerClasses"][0]
        for j in range(u2(p)):
            ic, oc, nm, fl = struct.unpack(">HHHH", data[p + 2 + 8 * j:p + 10 + 8 * j])
            inner.append({"inner": cls(ic), "outer": cls(oc), "name": utf8(nm) if nm else None, "access": fl})
    record = None
    if "Record" in attrs:
        p, record = attrs["Record"][0], []
        q = p + 2
        for _ in range(u2(p)):
            name, desc = utf8(u2(q)), utf8(u2(q + 2))
            sub, q = attributes(q + 4)
            record.append({"name": name, "desc": desc,
                           "signature": utf8(u2(sub["Signature"][0])) if "Signature" in sub else None})
    return {"name": cls(this), "access": access, "super": cls(sup), "interfaces": interfaces,
            "signature": signature, "members": members, "inner": inner, "record": record, "ids": ids}


def clinit_ids(code, pool, owner):
    """What a class's static initializer says of each static field it sets, from the instructions just before: the
    last string loaded since the field before (its registry id, `Items.IRON_INGOT` is "iron_ingot"), the last class
    loaded (an enum property's values), and the static field it copies, when it sets the field straight from another
    (`RotatedPillarBlock.AXIS` is `BlockStateProperties.AXIS`). Names only: the code isn't kept."""
    found, last, klass, copied, i = {}, None, None, None, 0
    while i < len(code):
        op = code[i]
        just_copied = None
        if op in (0x12, 0x13):  # ldc, ldc_w
            k = code[i + 1] if op == 0x12 else struct.unpack(">H", code[i + 1:i + 3])[0]
            entry = pool[k]
            if entry and entry[0] == 8:
                last = pool[entry[1]][1]
            elif entry and entry[0] == 7:
                klass = pool[entry[1]][1]
        elif op == 0xB2:  # getstatic
            ref = pool[struct.unpack(">H", code[i + 1:i + 3])[0]]
            nat = pool[ref[2]]
            just_copied = (pool[pool[ref[1]][1]][1], pool[nat[1]][1], pool[nat[2]][1])
        elif op == 0xB3:  # putstatic
            ref = pool[struct.unpack(">H", code[i + 1:i + 3])[0]]
            if pool[pool[ref[1]][1]][1] == owner:
                found[pool[pool[ref[2]][1]][1]] = {"id": last, "class": klass, "copies": copied}
            last = klass = None
        copied = just_copied
        i += op_length(code, i)
    return found


def op_length(code, i):
    """How many bytes the instruction at `i` takes."""
    op = code[i]
    if op in (0x10, 0x12, 0x15, 0x16, 0x17, 0x18, 0x19, 0x36, 0x37, 0x38, 0x39, 0x3A, 0xA9, 0xBC):
        return 2
    if op in (0x11, 0x13, 0x14, 0x84, 0xBB, 0xBD, 0xC0, 0xC1, 0xC6, 0xC7) or 0x99 <= op <= 0xA8 or 0xB2 <= op <= 0xB8:
        return 3
    if op in (0xB9, 0xBA, 0xC8, 0xC9):
        return 5
    if op == 0xC5:
        return 4
    if op == 0xC4:  # wide
        return 6 if code[i + 1] == 0x84 else 4
    if op in (0xAA, 0xAB):  # tableswitch, lookupswitch
        p = i + 1 + (3 - i % 4)
        if op == 0xAA:
            low, high = struct.unpack(">ii", code[p + 4:p + 12])
            return p + 12 + 4 * (high - low + 1) - i
        (n,) = struct.unpack(">i", code[p + 4:p + 8])
        return p + 8 + 8 * n - i
    return 1


class Jars:
    """Class files by name, from jars (and the jars inside them), parsed when first asked for."""

    def __init__(self, jars):
        self.where, self.cache, self.zips = {}, {}, []
        for jar in jars:
            self._index(zipfile.ZipFile(jar))

    def _index(self, z):
        self.zips.append(z)
        for name in z.namelist():
            if name.endswith(".class") and not name.startswith("META-INF/"):
                self.where.setdefault(name[:-6], z)
            elif name.startswith("META-INF/jars/") and name.endswith(".jar"):
                self._index(zipfile.ZipFile(io.BytesIO(z.read(name))))

    def __contains__(self, name):
        return name in self.where

    def get(self, name):
        if name not in self.cache:
            z = self.where.get(name)
            try:
                self.cache[name] = parse(z.read(name + ".class")) if z else None
            except (ValueError, IndexError, struct.error):
                self.cache[name] = None
        return self.cache[name]

    def names(self):
        return list(self.where)


