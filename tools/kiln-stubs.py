def source_name(binary):
    return binary.replace("/", ".").replace("$", ".")


class Sig:
    """A descriptor or generic signature, as Java source; the classes it names collect in `used`."""

    def __init__(self, text, used, known=None):
        self.s, self.i, self.used, self.known = text, 0, used, known

    def peek(self):
        return self.s[self.i] if self.i < len(self.s) else ""

    def ident(self, stops):
        start = self.i
        while self.i < len(self.s) and self.s[self.i] not in stops:
            self.i += 1
        return self.s[start:self.i]

    def type_params(self):
        if self.peek() != "<":
            return []
        self.i += 1
        params = []
        while self.peek() != ">":
            name = self.ident(":")
            bounds = []
            self.i += 1
            if self.peek() not in (":",):
                bounds.append(self.ref())
            while self.peek() == ":":
                self.i += 1
                bounds.append(self.ref())
            params.append(name + (" extends " + " & ".join(bounds) if bounds and bounds != ["java.lang.Object"] else ""))
        self.i += 1
        return params

    def java(self):
        c = self.peek()
        if c in PRIMITIVES:
            self.i += 1
            return PRIMITIVES[c]
        return self.ref()

    def ref(self):
        c = self.peek()
        if c == "L":
            return self.class_type()
        if c == "T":
            self.i += 1
            name = self.ident(";")
            self.i += 1
            return name
        if c == "[":
            self.i += 1
            return self.java() + "[]"
        raise ValueError(f"bad signature {self.s!r} at {self.i}")

    def class_type(self):
        self.i += 1
        binary = self.ident("<.;")
        out = source_name(binary)
        if self.peek() == "<":
            out += self.type_args()
        while self.peek() == ".":
            self.i += 1
            simple = self.ident("<.;")
            binary += "$" + simple
            out += "." + simple
            if self.peek() == "<":
                out += self.type_args()
        self.i += 1
        self.used.add(binary)
        # A class there is no stand-in for (a library Kiln doesn't have): Object in its place.
        if self.known and not self.known(binary):
            return "java.lang.Object"
        return out

    def type_args(self):
        self.i += 1
        args = []
        while self.peek() != ">":
            c = self.peek()
            if c == "*":
                self.i += 1
                args.append("?")
            elif c == "+":
                self.i += 1
                args.append("? extends " + self.ref())
            elif c == "-":
                self.i += 1
                args.append("? super " + self.ref())
            else:
                args.append(self.ref())
        self.i += 1
        return "<" + ", ".join(args) + ">"

    def method(self):
        params = self.type_params()
        self.i += 1
        args = []
        while self.peek() != ")":
            args.append(self.java())
        self.i += 1
        result = self.java()
        return params, args, result


def erased(desc):
    """A descriptor's types as erased Java source names."""
    used = set()
    s = Sig(desc, used)
    if desc.startswith("("):
        _, args, result = s.method()
        return args, result
    return s.java()


