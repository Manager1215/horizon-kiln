class Writer:
    def __init__(self, plan):
        self.plan, self.game = plan, plan.game
        self.drop = set()  # (class, kind, name, desc) or (class, None, None, None) for a class's supertypes
        self.shells = set()  # classes made bare: a type with nothing in it

    def known(self, binary):
        return self.plan.available(binary)

    def files(self):
        """The generated files, and the hand-written ones with their generated regions: path -> (text, lines)."""
        tops, regions = {}, set(self.plan.hand_extra)
        for name in self.plan.classes:
            top = name.split("$")[0]
            if self.plan.hand(top):
                outer = name.rsplit("$", 1)[0]
                if self.plan.hand(outer) and outer in self.plan.kiln:
                    regions.add(outer)
                continue
            tops.setdefault(top, []).append(name)
        out = {}
        for top in sorted(tops):
            buf, lines = [], {}
            package = top.rsplit("/", 1)[0].replace("/", ".")
            buf.append(HEADER)
            buf.append(f"package {package};\n")
            self.write_class(top, buf, lines, 0)
            text = "\n".join(buf) + "\n"
            out[OUT / (top + ".java")] = (text, lines)
        by_file = {}
        for h in regions:
            by_file.setdefault(h.split("$")[0], []).append(h)
        for top, classes in by_file.items():
            path = HAND / (top + ".java")
            text = self.originals[path]
            inserts = []
            for h in classes:
                at, depth = body_end(text, top, h)
                if at is None:
                    self.plan.report["hand_nested"].add(h)
                    continue
                buf, lines = [], {}
                self.write_region(h, buf, lines, depth)
                inserts.append((at, "\n".join(buf) + "\n", lines))
            inserts.sort(key=lambda x: x[0])
            result, mapping, last, added = [], {}, 0, 0
            for brace, region, lines in inserts:
                # On the closing brace's line when it stands alone there, else before the brace on a line of its own.
                line_start = text.rfind("\n", 0, brace) + 1
                at, prefix = (line_start, "") if not text[line_start:brace].strip() else (brace, "\n")
                result.append(text[last:at])
                first = text[:at].count("\n") + 1 + added + len(prefix)
                for k, owner in lines.items():
                    mapping[first + k - 1] = owner
                result.append(prefix + region)
                added += (prefix + region).count("\n")
                last = at
            result.append(text[last:])
            out[path] = ("".join(result), mapping)
        return out

    def write_region(self, h, buf, lines, depth):
        """What the hand-written class `h` lacks, inside it: members, then nested classes."""
        info = self.game.get(h)
        ind = "    " * (depth + 1)
        self.emit(buf, lines, ind + REGION_START, (h, None))
        is_interface = bool(info and info["access"] & INTERFACE)
        wanted = self.plan.hand_extra.get(h, set())
        for m in info["members"] if info else []:
            key = (m["kind"], m["name"], m["desc"])
            if key not in wanted or (h,) + key in self.drop or m["access"] & (SYNTHETIC | BRIDGE):
                continue
            if m["kind"] == "field":
                self.emit(buf, lines, ind + self.field(h, m, is_interface), (h, m))
            elif m["name"] != "<init>":
                text = self.method(h, m, is_interface, bool(info["access"] & ENUM), concrete=True)
                self.emit(buf, lines, ind + text, (h, m))
        for ic in self.nested_of(h) if info else []:
            if not (self.plan.hand(ic["inner"]) and ic["inner"] in self.plan.kiln):
                self.write_class(ic["inner"], buf, lines, depth + 1)
        self.emit(buf, lines, ind + REGION_END, (h, None))

    def nested_of(self, name):
        info = self.game.get(name)
        found = []
        for ic in info["inner"]:
            if ic["outer"] == name and ic["name"] and ic["inner"] in self.plan.classes:
                found.append(ic)
        return found

    def flags_as_nested(self, name):
        outer = name.rsplit("$", 1)[0]
        for ic in (self.game.get(outer) or {}).get("inner", []):
            if ic["inner"] == name:
                return ic["access"]
        return None

    def write_class(self, name, buf, lines, depth):
        info = self.game.get(name)
        ind = "    " * depth
        nested_flags = self.flags_as_nested(name) if "$" in name else None
        access = nested_flags if nested_flags is not None else info["access"]
        simple = name.rsplit("$", 1)[-1] if "$" in name else name.rsplit("/", 1)[-1]
        used = set()
        type_params, parent, faces = [], None, []
        if info["signature"]:
            s = Sig(info["signature"], used, self.known)
            type_params = s.type_params()
            parent = s.ref()
            while s.peek():
                faces.append(s.ref())
        else:
            parent = source_name(info["super"]) if info["super"] else None
            faces = [source_name(i) for i in info["interfaces"]]
        dropped_parents = (name, None, None, None) in self.drop
        is_interface = info["access"] & INTERFACE
        is_annotation = info["access"] & ANNOTATION
        is_enum = info["access"] & ENUM and info["super"] == "java/lang/Enum"
        is_record = info["record"] is not None and info["super"] == "java/lang/Record"
        widened = (name, "class", None, None) in self.plan.widened
        mods = "public " if access & (PUBLIC | PROTECTED) or depth == 0 or widened else ""
        if depth > 0 and (access & STATIC or is_interface or is_enum or is_record):
            mods += "static "
        tp = "<" + ", ".join(type_params) + ">" if type_params else ""
        if dropped_parents:
            faces = []
            parent = None if not is_enum and not is_record else parent
        if name in self.shells:
            kind = "interface" if is_interface else "enum" if is_enum else "abstract class" \
                if info["access"] & ABSTRACT else "class"
            self.emit(buf, lines, f"{ind}{mods}{kind} {simple}{'' if is_enum else tp} {{", (name, None))
            if is_enum:
                constants = [m["name"] for m in info["members"] if m["kind"] == "field" and m["access"] & ENUM]
                self.emit(buf, lines, f"{ind}    " + ", ".join(constants) + ";", (name, None))
            elif not is_interface:
                self.emit(buf, lines, f"{ind}    protected {simple}() {{}}", (name, None))
            for ic in self.nested_of(name):
                self.write_class(ic["inner"], buf, lines, depth + 1)
            self.emit(buf, lines, ind + "}", (name, None))
            return
        if is_annotation:
            head = f"{ind}{mods}@interface {simple} {{"
        elif is_interface:
            ext = " extends " + ", ".join(faces) if faces else ""
            head = f"{ind}{mods}interface {simple}{tp}{ext} {{"
        elif is_enum:
            impl = " implements " + ", ".join(faces) if faces else ""
            head = f"{ind}{mods}enum {simple}{impl} {{"
        elif is_record:
            comps = ", ".join(f"{Sig(c['signature'] or c['desc'], set(), self.known).java()} {c['name']}"
                              for c in info["record"])
            impl = " implements " + ", ".join(faces) if faces else ""
            head = f"{ind}{mods}record {simple}{tp}({comps}){impl} {{"
        else:
            abstract = "abstract " if info["access"] & ABSTRACT else ""
            ext = f" extends {parent}" if parent and parent != "java.lang.Object" else ""
            impl = " implements " + ", ".join(faces) if faces else ""
            head = f"{ind}{mods}{abstract}class {simple}{tp}{ext}{impl} {{"
        self.emit(buf, lines, head, (name, None))
        wanted = self.plan.classes.get(name, set())
        members = [m for m in info["members"] if (m["kind"], m["name"], m["desc"]) in wanted
                   and (name, m["kind"], m["name"], m["desc"]) not in self.drop]
        if is_enum:
            constants = [m["name"] for m in info["members"] if m["kind"] == "field" and m["access"] & ENUM]
            self.emit(buf, lines, f"{ind}    " + (", ".join(constants) or "") + ";", (name, None))
        if is_annotation:
            members = []
        has_no_arg = False
        for m in members:
            if m["access"] & (SYNTHETIC | BRIDGE) or m["name"] == "<clinit>":
                continue
            widened = (name, m["kind"], m["name"], m["desc"]) in self.plan.widened
            if not widened and (m["access"] & PRIVATE or not m["access"] & (PUBLIC | PROTECTED) and not is_interface):
                continue
            if m["kind"] == "field":
                if is_enum and m["access"] & ENUM:
                    continue
                self.emit(buf, lines, ind + "    " + self.field(name, m, is_interface), (name, m))
            elif m["name"] == "<init>":
                if is_record and m["desc"] != "(" + "".join(c["desc"] for c in info["record"]) + ")V":
                    self.emit(buf, lines, ind + "    " + self.record_constructor(info, simple, m), (name, m))
                    continue
                if is_enum or is_record or is_interface:
                    continue
                text, no_arg = self.constructor(name, simple, m, nested_flags)
                has_no_arg = has_no_arg or no_arg
                self.emit(buf, lines, ind + "    " + text, (name, m))
            else:
                if is_record and any(c["name"] == m["name"] for c in info["record"]) and m["desc"].startswith("()"):
                    continue
                if is_enum and m["name"] in ("values", "valueOf"):
                    continue
                self.emit(buf, lines, ind + "    " + self.method(name, m, is_interface, is_enum), (name, m))
        if not (is_interface or is_enum or is_record or is_annotation or has_no_arg):
            self.emit(buf, lines, ind + "    " + self.no_arg(name, simple), (name, None))
        for ic in self.nested_of(name):
            self.write_class(ic["inner"], buf, lines, depth + 1)
        self.emit(buf, lines, ind + "}", (name, None))

    def emit(self, buf, lines, text, owner):
        start = sum(b.count("\n") + 1 for b in buf) + 1
        buf.append(text)
        for k in range(text.count("\n") + 1):
            lines[start + k] = owner

    def field(self, owner, m, in_interface):
        t = Sig(m["signature"] or m["desc"], set(), self.known).java()
        static = m["access"] & STATIC or in_interface
        public = m["access"] & PUBLIC or in_interface or (owner, "field", m["name"], m["desc"]) in self.plan.widened
        mods = ("public " if public else "protected ") + ("static " if static else "")
        if static and m["access"] & FINAL or in_interface:
            mods += "final "
        value = literal(m["constant"], m["desc"]) if m["constant"] is not None else default(t)
        factory = self.factory(owner, m) if static and m["constant"] is None else None
        if factory:
            value = factory
        elif static and m["constant"] is None and self.copies(owner, m):
            value = self.copies(owner, m)
        elif static and m["desc"] == "Lnet/minecraft/world/level/block/state/properties/EnumProperty;" \
                and self.clinit(owner, m).get("class") and self.known(self.clinit(owner, m)["class"]):
            value = (f'net.minecraft.world.level.block.state.properties.EnumProperty.create("{self.constant_id(owner, m)}", '
                     f'{source_name(self.clinit(owner, m)["class"])}.class)')
        elif static and m["desc"] == "Lnet/fabricmc/fabric/api/event/Event;" and m["signature"]:
            listener = Sig(m["signature"], set(), self.known).java()
            inner = listener[listener.index("<") + 1:listener.rindex(">")] if "<" in listener else ""
            if inner and "<" not in inner and inner != "java.lang.Object":
                value = f"kiln.Constants.event({inner}.class)"
        elif static and m["desc"] == "Lnet/minecraft/world/level/block/WeatheringCopperCollection;" \
                and owner in ("net/minecraft/world/level/block/Blocks", "net/minecraft/world/item/Items"):
            # A copper block's weather states (`Blocks.CUT_COPPER`): the game's blocks or items by their ids.
            kind = "Blocks" if owner.endswith("Blocks") else "Items"
            value = f'kiln.Constants.copper{kind}("{m["name"].lower()}")'
        elif static and m["desc"] == "Lnet/minecraft/resources/ResourceKey;" and m["signature"] \
                and "Lnet/minecraft/core/Registry<" in m["signature"]:
            # A registry's key (`EquipmentAssets.ROOT_ID`): by the id the game's static initializer gives it.
            rid = self.clinit(owner, m).get("id") or m["name"].lower()
            value = ('net.minecraft.resources.ResourceKey.createRegistryKey('
                     f'net.minecraft.resources.Identifier.withDefaultNamespace("{rid}"))')
        elif static and m["constant"] is None and m["desc"] in CODECS:
            value = f'{CODECS[m["desc"]]}("{source_name(owner)}.{m["name"]}")'
        elif static and m["constant"] is None and m["desc"] in CONSTANTS:
            value = f'{CONSTANTS[m["desc"]]}("{self.constant_id(owner, m)}")'
        if static and value == "null" and self.made_new(m["desc"], owner):
            # A static field of a plain class anyone can make (`ItemModels.ID_MAPPER`): one, so calls on it go on.
            value = f"new {source_name(m['desc'][1:-1])}{'<>' if '<' in t else ''}()"
        elif static and value == "null" and self.empty_record(m["desc"]):
            # A record constant (`ItemAttributeModifiers.EMPTY`): one with nothing in it.
            value = self.empty_record(m["desc"])
        if not static and not m["access"] & FINAL:
            return f"{mods}{t} {m['name']};"
        if not static:
            return f"{mods}{t} {m['name']};"
        return f"{mods}{t} {m['name']} = {value};"

    def any_interface(self, desc):
        """Whether a descriptor names a public interface: java.util.function's, or the game's."""
        name = desc[1:-1] if desc.startswith("L") and desc.endswith(";") else None
        if not name:
            return False
        if name.startswith("java/util/function/"):
            return True
        info = self.game.get(name)
        if not info or not info["access"] & INTERFACE or info["access"] & ANNOTATION or name in self.shells:
            return False
        if name not in self.plan.classes and not self.plan.hand(name):
            return False
        flags = self.flags_as_nested(name) if "$" in name else info["access"]
        return bool((flags or 0) & PUBLIC)

    def empty_record(self, desc):
        """`new R(null, 0, ...)` for a generated record R a descriptor names, else None."""
        name = desc[1:-1] if desc.startswith("L") and desc.endswith(";") else None
        info = self.game.get(name) if name else None
        if not info or info["record"] is None or info["super"] != "java/lang/Record" or name not in self.plan.classes \
                or self.plan.hand(name) or name in self.shells or (name, None, None, None) in self.drop:
            return None
        if "$" in name and not (self.flags_as_nested(name) or 0) & STATIC:
            return None
        generic = info["signature"] and info["signature"].startswith("<")
        return f"new {source_name(name)}{'<>' if generic else ''}({self.record_args(info, [])})"

    def made_new(self, desc, owner):
        """Whether `owner` can write `new X()` for the class a descriptor names: one generated here, concrete, with a
        public constructor without arguments, or the generated protected one in `owner`'s own package."""
        if not desc.startswith("L") or not desc.endswith(";"):
            return False
        name = desc[1:-1]
        if "$" in name and not (self.flags_as_nested(name) or 0) & STATIC:
            return False
        info = self.game.get(name)
        if not info or name not in self.plan.classes or self.plan.hand(name) or name in self.shells:
            return False
        if info["access"] & (INTERFACE | ABSTRACT | ENUM) or info["record"] is not None:
            return False
        if (name, None, None, None) in self.drop:
            return False
        if name.rsplit("/", 1)[0] == owner.rsplit("/", 1)[0]:
            return True
        return any(m["name"] == "<init>" and m["desc"] == "()V" and m["access"] & PUBLIC
                   and (name, "method", "<init>", "()V") not in self.drop for m in info["members"])

    def own_params(self, owner):
        """The class's own type parameters as a use writes them: `<B, V>`, or nothing."""
        info = self.game.get(owner)
        if not info or not info["signature"] or not info["signature"].startswith("<"):
            return ""
        params = Sig(info["signature"], set(), self.known).type_params()
        return "<" + ", ".join(p.split(" ")[0] for p in params) + ">"

    def record_args(self, info, args):
        """A record's components from a factory's arguments: each by its type, in order; a default where none fits."""
        mine = [a.split("<")[0].replace("...", "[]") for a in args]
        used, out = set(), []
        for c in info["record"]:
            t = Sig(c["desc"], set(), self.known).java()
            full = Sig(c["signature"] or c["desc"], set(), self.known).java()
            k = next((i for i, a in enumerate(mine) if a == t and i not in used), None)
            if k is not None:
                used.add(k)
                # The same class with other type arguments (`MapCodec<P>` for `MapCodec<UnbakedSwitch<P, T>>`): raw.
                out.append(f"p{k}" if args[k].replace("...", "[]") == full or "<" not in full else f"({t}) p{k}")
            elif c["desc"] in CODECS:
                out.append(f'{CODECS[c["desc"]]}("{source_name(info["name"])}.{c["name"]}")')
            else:
                out.append(f"({t}) {default(t)}")
        return ", ".join(out)

    def clinit(self, owner, m):
        return (self.game.get(owner) or {}).get("ids", {}).get(m["name"], {})

    def constant_id(self, owner, m):
        """A registered constant's id: the string the game's static initializer loaded last before setting it, if it
        ends with the constant's name ("block.anvil.use" for ANVIL_USE, not "empty" before FLUID), else the name."""
        loaded = self.clinit(owner, m).get("id") or ""
        flat = re.sub(r"[^a-z0-9]", "", loaded.lower())
        name = m["name"].lower()
        return loaded if flat and flat.endswith(name.replace("_", "")) else name

    def copies(self, owner, m):
        """The static field the game sets this one from (`RotatedPillarBlock.AXIS = BlockStateProperties.AXIS`), as
        source, when that one is there too and of the same type."""
        ref = self.clinit(owner, m).get("copies")
        if not ref or ref[2] != m["desc"] or ref[0] == owner or not self.known(ref[0]):
            return None
        there = ref[0] in self.plan.kiln and kiln_has(self.plan.kiln, ref[0], "field", ref[1], ref[2]) or \
            ("field", ref[1], ref[2]) in self.plan.classes.get(ref[0], set()) or \
            ("field", ref[1], ref[2]) in self.plan.hand_extra.get(ref[0], set())
        return f"{source_name(ref[0])}.{ref[1]}" if there else None

    def factory(self, owner, m):
        """A hand-written registry class's constant made as its others are: its factory (`Items.register(String)`)
        with the id the game's static initializer gives it, or its name in lower case."""
        if not self.plan.hand(owner) or owner not in self.plan.kiln:
            return None
        made = [n for n, d in self.plan.kiln[owner]["declared"] if d == "(Ljava/lang/String;)" + m["desc"]]
        if not made:
            return None
        return f'{made[0]}("{self.constant_id(owner, m)}")'

    def params(self, m, skip_outer=False):
        params, args, result = Sig(m["signature"] or m["desc"], set(), self.known).method()
        if skip_outer and not m["signature"]:
            args = args[1:]
        if m["access"] & VARARGS and args and args[-1].endswith("[]"):
            args[-1] = args[-1][:-2] + "..."
        return params, args, result

    def method(self, owner, m, in_interface, in_enum, concrete=False):
        """A method with a body that logs and gives back a default; `concrete` (in a hand-written class, whose own
        subclasses don't have it) gives an abstract one a body too."""
        tps, args, result = self.params(m)
        tp = "<" + ", ".join(tps) + "> " if tps else ""
        decl = ", ".join(f"{a} p{i}" for i, a in enumerate(args))
        static = m["access"] & STATIC
        if in_interface:
            if m["access"] & ABSTRACT and not concrete:
                return f"{tp}{result} {m['name']}({decl});"
            mods = "static " if static else "default "
        else:
            public = m["access"] & PUBLIC or (owner, "method", m["name"], m["desc"]) in self.plan.widened
            mods = "public " if public else "protected "
            if static:
                mods += "static "
            if m["access"] & ABSTRACT and not in_enum and not concrete:
                return f"{mods}abstract {tp}{result} {m['name']}({decl});"
        call = f'kiln.Missing.called("{source_name(owner)}.{m["name"]}");'
        if result == "void":
            return f"{mods}{tp}void {m['name']}({decl}) {{ {call} }}"
        own = source_name(owner)
        info = self.game.get(owner)
        plain = info and not info["access"] & (INTERFACE | ABSTRACT | ENUM) and info["record"] is None \
            and owner not in self.shells and not self.plan.hand(owner)
        nested = self.flags_as_nested(owner) if "$" in owner else None
        if not static and result in (own, own + self.own_params(owner)):
            # A builder's method: itself, so the chain goes on (only when the type is its own, parameters and all).
            value = "this"
        elif static and plain and result.split("<")[0] == own and (nested is None or nested & STATIC):
            # A static factory of its own class (a builder's start): a new one, so the chain goes on.
            value = f"new {own}{'<>' if '<' in result else ''}()"
        elif static and self.made_new(m["desc"].split(")")[-1], owner):
            # A static factory of another class it can make (`ItemAttributeModifiers.builder()`): a new one.
            value = f"new {result.split('<')[0]}{'<>' if '<' in result else ''}()"
        elif static and self.any_interface(m["desc"].split(")")[-1]):
            # A static factory of an interface (`BiomeSelectors.tag(...)`, a `Predicate`): one that does nothing.
            value = f"kiln.Constants.nothing({result.split('<')[0]}.class)"
        elif self.empty_record(m["desc"].split(")")[-1]):
            # A generated record (a builder's `build()`): one with nothing in it, so calls on it go on.
            value = self.empty_record(m["desc"].split(")")[-1])
        elif static and info and info["access"] & INTERFACE and not info["access"] & ANNOTATION \
                and result.split("<")[0] == own and not self.plan.hand(owner) and (nested is None or nested & STATIC):
            # An interface's static factory (`getDefaultInstance()`): an instance that does nothing, so calls go on.
            value = f"kiln.Constants.nothing({own}.class)"
        elif static and info and info["record"] is not None and result.split("<")[0] == own \
                and owner not in self.shells:
            # A record's factory (`UniformInt.of(0, 2)`): the record itself, from the arguments that fit.
            value = f"new {own}{'<>' if '<' in result else ''}({self.record_args(info, args)})"
        elif m["desc"].split(")")[-1] in CODECS:
            # A codec (`Codec.dispatch(...)`, `codec()`): one a mod can build on, failing only on a value.
            value = f'{CODECS[m["desc"].split(")")[-1]]}("{source_name(owner)}.{m["name"]}")'
        else:
            value = default(result)
        if value not in ("this", "null") and value not in DEFAULTS.values() and not value.startswith(("new ", "kiln.")):
            value = "null"
        return f"{mods}{tp}{result} {m['name']}({decl}) {{ {call} return {value}; }}"

    def constructor(self, owner, simple, m, nested_flags):
        inner = nested_flags is not None and not nested_flags & STATIC
        tps, args, _ = self.params(m, skip_outer=inner)
        tp = "<" + ", ".join(tps) + "> " if tps else ""
        decl = ", ".join(f"{a} p{i}" for i, a in enumerate(args))
        public = m["access"] & PUBLIC or (owner, "method", "<init>", m["desc"]) in self.plan.widened
        mods = "public " if public else "protected "
        return f"{mods}{tp}{simple}({decl}) {{ {self.super_call(owner, args)} }}", not args

    def record_constructor(self, info, simple, m):
        """A record's other constructor: its arguments passed on to the canonical one, each by its type."""
        tps, args, _ = self.params(m)
        tp = "<" + ", ".join(tps) + "> " if tps else ""
        decl = ", ".join(f"{a} p{i}" for i, a in enumerate(args))
        return f"public {tp}{simple}({decl}) {{ this({self.record_args(info, args)}); }}"

    def no_arg(self, owner, simple):
        return f"protected {simple}() {{ {self.super_call(owner, [])} }}"

    def super_call(self, owner, args):
        """`super(...)` with what the parent's best constructor takes: this constructor's arguments where the types
        match, else defaults."""
        info = self.game.get(owner)
        parent = info["super"]
        if not parent or parent == "java/lang/Object" or (owner, None, None, None) in self.drop:
            return ""
        if info["access"] & ENUM or info["record"] is not None:
            return ""
        options = []
        if self.plan.hand(parent):
            c = self.plan.kiln.get(parent)
            for name, desc in (c["declared"] if c else []):
                if name == "<init>" and (parent, desc) in self.plan.kiln_ctor_access:
                    options.append(erased(desc)[0])
        elif parent in self.shells:
            options = [[]]
        elif parent in self.plan.classes:
            options = [[]]
            for m in self.game.get(parent)["members"]:
                if m["name"] == "<init>" and m["access"] & (PUBLIC | PROTECTED) and \
                        (parent, "method", "<init>", m["desc"]) not in self.drop:
                    flags = self.flags_as_nested(parent)
                    inner = flags is not None and not flags & STATIC
                    options.append(erased(m["desc"])[0][1 if inner else 0:])
        if not options:
            return ""
        mine = [a.split("<")[0].replace("...", "[]") for a in args]

        def score(option):
            return (sum(1 for t in option if t in mine), -len(option))

        best = max(options, key=score)
        passed, used = [], set()
        for t in best:
            k = next((i for i, a in enumerate(mine) if a == t and i not in used), None)
            if k is not None:
                used.add(k)
                passed.append(f"p{k}")
            else:
                passed.append(f"({t}) {default(t)}" if t in DEFAULTS else f"({t}) null")
        return f"super({', '.join(passed)});"


def body_end(text, top, name):
    """Where the closing brace of class `name`'s body is in its top-level source `text` (the start of its line), and
    how deep it is nested; (None, 0) when the source doesn't have it."""
    start, end, depth = 0, len(text), 0
    for simple in name[len(top) + 1:].split("$") if name != top else []:
        m = re.compile(r"\b(class|interface|enum|record)\s+" + re.escape(simple) + r"\b").search(text, start, end)
        if not m:
            return None, 0
        open_at = text.index("{", m.end())
        start, end = open_at + 1, matching(text, open_at)
        depth += 1
    close = text.rindex("}", 0, len(text)) if name == top else end
    return close, depth


def matching(text, open_at):
    """The index of the brace closing the one at `open_at`, past strings, characters and comments."""
    level, i = 0, open_at
    while i < len(text):
        c = text[i]
        if text.startswith("//", i):
            i = text.index("\n", i)
        elif text.startswith("/*", i):
            i = text.index("*/", i) + 1
        elif c in "\"'":
            j = i + 1
            while text[j] != c:
                j += 2 if text[j] == "\\" else 1
            i = j
        elif c == "{":
            level += 1
        elif c == "}":
            level -= 1
            if level == 0:
                return i
        i += 1
    raise ValueError("unbalanced braces")


def default(t):
    return DEFAULTS.get(t, "null")


def literal(value, desc):
    if desc == "Ljava/lang/String;":
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'
    if desc == "Z":
        return "true" if value else "false"
    if desc == "C":
        return f"(char) {value}"
    if desc == "J":
        return f"{value}L"
    if desc in ("F", "D"):
        suffix = "F" if desc == "F" else "D"
        box = "Float" if desc == "F" else "Double"
        if value != value:
            return f"{box}.NaN"
        if value in (float("inf"), float("-inf")):
            return f"{box}.{'POSITIVE' if value > 0 else 'NEGATIVE'}_INFINITY"
        return repr(float(value)) + suffix
    if desc in ("B", "S"):
        return f"({PRIMITIVES[desc]}) {value}"
    return str(value)


