class Plan:
    def __init__(self, game, kiln, libs):
        self.game, self.kiln, self.libs = game, kiln, libs
        self.classes = {}  # binary name -> set of (kind, name, desc) to include
        self.queue = []
        self.hand_extra = {}  # hand-written class -> members generated into it
        self.widened = set()  # (class, kind, name, desc) a mod's access widener makes public
        self.report = {"hand_members": set(), "hand_nested": set(), "unknown": set(), "dropped": [],
                       "widened": set()}

    def hand(self, name):
        """A hand-written stand-in's class (its top-level source is in kiln/java)."""
        top = name.split("$")[0]
        return (HAND / (top + ".java")).is_file()

    def available(self, name):
        if name.startswith(("java/", "javax/", "jdk/", "sun/")):
            return True
        if name in self.libs or (self.hand(name) and name in self.kiln):
            return True
        return name in self.classes

    def want(self, name, members=()):
        """Make `name`, with `members` (expanded later, by `drain`); False when it can't be made."""
        if name.startswith(("java/", "javax/", "jdk/", "sun/")) or name in self.libs:
            return True
        if self.hand(name) and name in self.kiln:
            for m in members:
                self.extra(name, m)
            return True
        if name not in self.game:
            self.report["unknown"].add(name)
            return False
        entry = self.classes.get(name)
        if entry is None:
            entry = self.classes[name] = set()
            self.queue.append(("class", name, None))
        for m in members:
            if m not in entry:
                entry.add(m)
                self.queue.append(("member", name, m))
        return True

    def extra(self, name, m):
        """A member the mods use that the hand-written `name` lacks: generated into it."""
        if m[1] == "<init>":
            self.report["hand_members"].add((name,) + m)
            return
        entry = self.hand_extra.setdefault(name, set())
        if m not in entry:
            entry.add(m)
            self.queue.append(("member", name, m))

    def drain(self):
        """Everything the wanted classes and members need: their outer classes, parents, types; an interface's
        abstract methods, an enum's constants, a class's constructors."""
        while self.queue:
            what, name, m = self.queue.pop()
            info = self.game.get(name)
            if what == "member":
                found = self.member(name, *m)
                for t in self.types_of_member(found) if found else ():
                    self.want(t)
                # A static field the game sets from another class's (`RotatedPillarBlock.AXIS`): that one too.
                copies = (info or {}).get("ids", {}).get(m[1], {}).get("copies") if m[0] == "field" else None
                if copies and copies[0] != name:
                    self.use(copies[0], "field", copies[1], copies[2])
                continue
            if "$" in name:
                self.want(name.rsplit("$", 1)[0])
            for parent in [info["super"]] + info["interfaces"]:
                if parent:
                    self.want(parent)
            for t in self.types_of_class(info):
                self.want(t)
            own = []
            for x in info["members"]:
                if x["kind"] == "method" and info["access"] & INTERFACE and x["access"] & ABSTRACT:
                    own.append(("method", x["name"], x["desc"]))
                elif x["kind"] == "field" and info["access"] & ENUM and x["access"] & ENUM:
                    own.append(("field", x["name"], x["desc"]))
                elif x["kind"] == "method" and x["name"] == "<init>" and x["access"] & (PUBLIC | PROTECTED):
                    own.append(("method", "<init>", x["desc"]))
            self.want(name, own)

    def types_of_class(self, info):
        used = set()
        if info["signature"]:
            s = Sig(info["signature"], used)
            s.type_params()
        for c in info["record"] or []:
            Sig(c["signature"] or c["desc"], used).java()
        return used

    def types_of_member(self, m):
        used = set()
        s = Sig(m["signature"] or m["desc"], used)
        if m["kind"] == "method":
            s.method()
        else:
            s.java()
        return used

    def member(self, owner, kind, name, desc):
        info = self.game.get(owner)
        for m in info["members"] if info else []:
            if m["kind"] == kind and m["name"] == name and m["desc"] == desc:
                return m
        return None

    def declaring(self, owner, kind, name, desc, seen=None):
        """The class in the game's hierarchy from `owner` that declares the member, or None."""
        seen = seen if seen is not None else set()
        if not owner or owner in seen:
            return None
        seen.add(owner)
        info = self.game.get(owner)
        if not info:
            return None
        if self.member(owner, kind, name, desc):
            return owner
        for parent in [info["super"]] + info["interfaces"]:
            found = self.declaring(parent, kind, name, desc, seen)
            if found:
                return found
        return None

    def use(self, owner, kind, name, desc):
        """A mod names this member: its declaring class gets it."""
        where = self.declaring(owner, kind, name, desc) or owner
        if self.hand(where) and where in self.kiln:
            if not kiln_has(self.kiln, where, kind, name, desc):
                self.extra(where, (kind, name, desc))
            return
        self.want(where, [(kind, name, desc)])


def kiln_has(kiln, owner, kind, name, desc):
    """Whether Kiln's hand-written `owner`, or what it extends, has the member (kiln-scan's rule)."""
    return SCAN.has_member(kiln, owner, name, desc, kind)


