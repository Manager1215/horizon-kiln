"""The catalogue's copy Kiln ships (kiln/java/kiln/catalogue.json, inside kiln-runtime.jar), for the overlay (D-113):
what a soft switch can stop of each mod tried (`softOff`, tools/soft-off.py) and whether horizon-kiln.cc lists it as
tried in the game, read by kiln/java/kiln/SoftOff.java.

    python3 -I tools/catalogue-snapshot.py           writes kiln/java/kiln/catalogue.json from catalogue/*.json
    python3 -I tools/catalogue-snapshot.py --check   exits 1 when the copy isn't what the catalogue says now

The copy has two maps:
- "jars": by a jar's SHA-256 (tried.json's jars), its mod's key in "mods" and its class;
- "mods": by a mod's name, letters and digits only (its catalogue id, its Modrinth slug, the jar's mod id where they
  differ), its status, the version and Kiln checked, and its class: a jar the catalogue hasn't, of a mod it has.
"generated" is the newest date in it, so a fresher copy (a refresh online) is told from an older one; "rules" is
tools/soft-off.py's RULES, so Kiln reads the jar itself when its own reading is newer than the copy's.
"""
import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "kiln" / "java" / "kiln" / "catalogue.json"

_spec = importlib.util.spec_from_file_location("soft_off", ROOT / "tools" / "soft-off.py")
soft_off = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(soft_off)


def snapshot():
    tried = json.loads((ROOT / "catalogue" / "tried.json").read_text())["mods"]
    verified = json.loads((ROOT / "catalogue" / "verified.json").read_text())["mods"]
    norm = soft_off.norm
    mods, jars, dates = {}, {}, []

    def put(names, entry):
        for name in names:
            if name and norm(name) not in mods:
                mods[norm(name)] = entry

    # Verified first: its status is the site's ("works", "doesnt-work", "in-development").
    for m in verified:
        checked = m.get("checked") or {}
        entry = {"name": m.get("name", m["id"]), "version": m.get("version", ""), "tried": m["status"],
                 "kiln": checked.get("kiln", ""), "date": checked.get("date", "")}
        if m.get("softOff"):
            entry["class"], entry["why"] = m["softOff"]["class"], m["softOff"]["why"]
        dates.append(entry["date"])
        put([m["id"], m.get("modrinth"), soft_off.ALIASES.get(m["id"])], entry)
    # Then every mod tried: works, or not yet (with why, on the site).
    for m in tried:
        result = m.get("result") or {}
        entry = {"name": m.get("name", m["id"]), "version": m.get("version", ""),
                 "tried": "works" if result.get("works") else "tried-not-working",
                 "kiln": result.get("kiln", ""), "date": result.get("date", "")}
        if m.get("softOff"):
            entry["class"], entry["why"] = m["softOff"]["class"], m["softOff"]["why"]
        dates.append(entry["date"])
        put([m["id"], m.get("modrinth")], entry)
        sha = (m.get("jar") or {}).get("sha256")
        if sha and m.get("softOff"):
            jars[sha] = {"mod": norm(m["id"]), "version": m.get("version", ""), "class": m["softOff"]["class"],
                         "why": m["softOff"]["why"]}
    return {
        "about": "Generated by tools/catalogue-snapshot.py from catalogue/verified.json and catalogue/tried.json; "
                 "read by kiln/java/kiln/SoftOff.java. Don't edit it by hand.",
        "generated": max(d for d in dates if d),
        "rules": soft_off.RULES,
        "jars": dict(sorted(jars.items())),
        "mods": dict(sorted(mods.items())),
    }


def main(argv):
    text = json.dumps(snapshot(), indent=1, ensure_ascii=False, sort_keys=False) + "\n"
    if "--check" in argv:
        if not OUT.is_file() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run python3 -I tools/catalogue-snapshot.py", file=sys.stderr)
            sys.exit(1)
        print(f"{OUT.relative_to(ROOT)} is current")
        return
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(json.loads(text)['jars'])} jars, {len(json.loads(text)['mods'])} names")


if __name__ == "__main__":
    main(sys.argv[1:])
