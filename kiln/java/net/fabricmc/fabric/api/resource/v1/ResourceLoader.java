    static boolean registerBuiltinPack(net.minecraft.resources.Identifier p0, net.fabricmc.loader.api.ModContainer p1, net.minecraft.network.chat.Component p2, net.fabricmc.fabric.api.resource.v1.pack.PackActivationType p3) { kiln.Missing.called("net.fabricmc.fabric.api.resource.v1.ResourceLoader.registerBuiltinPack"); return false; }
