package net.fabricmc.fabric.api.client.rendering.v1.level;

import kiln.Native;
import net.fabricmc.fabric.api.event.Event;

/**
 * Kiln's stand-in for Fabric's {@code LevelRenderEvents}: the level is drawn. The game draws it; Kiln tells the start
 * and the end of it each time it draws the mods' HUD (once a tick, in a world), before the HUD, as vanilla draws the
 * level before the HUD. What a listener draws into the level doesn't show.
 */
public final class LevelRenderEvents {
    public static final Event<StartMain> START_MAIN = Event.kiln$of(listeners -> context -> {
        for (StartMain l : listeners) {
            try {
                l.startMain(context);
            } catch (RuntimeException | LinkageError e) {
                Native.log("a START_MAIN listener threw " + e);
            }
        }
    });

    public static final Event<EndMain> END_MAIN = Event.kiln$of(listeners -> context -> {
        for (EndMain l : listeners) {
            try {
                l.endMain(context);
            } catch (RuntimeException | LinkageError e) {
                Native.log("an END_MAIN listener threw " + e);
            }
        }
    });

    private LevelRenderEvents() {}

    /** Kiln's own: the level drawn, as the mods hear it: its start, then its end. */
    public static void kiln$frame() {
        LevelRenderContext context = new LevelRenderContext() {};
        START_MAIN.invoker().startMain(context);
        END_MAIN.invoker().endMain(context);
    }

    @FunctionalInterface
    public interface StartMain {
        void startMain(LevelTerrainRenderContext context);
    }

    @FunctionalInterface
    public interface EndMain {
        void endMain(LevelRenderContext context);
    }
    // Generated by tools/kiln-stubs.py: what the mods use that isn't written by hand yet; names and signatures only.
    public static final net.fabricmc.fabric.api.event.Event<net.fabricmc.fabric.api.client.rendering.v1.level.LevelRenderEvents.BeforeBlockOutline> BEFORE_BLOCK_OUTLINE = kiln.Constants.event(net.fabricmc.fabric.api.client.rendering.v1.level.LevelRenderEvents.BeforeBlockOutline.class);
    public static interface BeforeBlockOutline {
        boolean beforeBlockOutline(net.fabricmc.fabric.api.client.rendering.v1.level.LevelRenderContext p0, net.minecraft.client.renderer.state.level.BlockOutlineRenderState p1);
    }
    // End of what tools/kiln-stubs.py generated.
}
