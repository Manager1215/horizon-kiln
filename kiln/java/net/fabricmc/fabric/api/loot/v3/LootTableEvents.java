package net.fabricmc.fabric.api.loot.v3;

import net.fabricmc.fabric.api.event.Event;
import net.minecraft.core.HolderLookup;
import net.minecraft.resources.ResourceKey;
import net.minecraft.world.level.storage.loot.LootTable;

/**
 * Kiln's stand-in for Fabric's {@code LootTableEvents}: a mod adds to the game's loot tables as they load. Kiln
 * keeps the listeners; turning what they add into loot Horizon reads is still to come (internal/server-side.md).
 */
public final class LootTableEvents {
    public static final Event<Modify> MODIFY = Event.kiln$of(listeners -> (key, table, source, registries) -> {
        for (Modify l : listeners) {
            l.modifyLootTable(key, table, source, registries);
        }
    });

    private LootTableEvents() {}

    @FunctionalInterface
    public interface Modify {
        void modifyLootTable(ResourceKey<LootTable> key, LootTable.Builder table, LootTableSource source,
                HolderLookup.Provider registries);
    }
    // Generated by tools/kiln-stubs.py: what the mods use that isn't written by hand yet; names and signatures only.
    public static final net.fabricmc.fabric.api.event.Event<net.fabricmc.fabric.api.loot.v3.LootTableEvents.Replace> REPLACE = kiln.Constants.event(net.fabricmc.fabric.api.loot.v3.LootTableEvents.Replace.class);
    public static final net.fabricmc.fabric.api.event.Event<net.fabricmc.fabric.api.loot.v3.LootTableEvents.ModifyDrops> MODIFY_DROPS = kiln.Constants.event(net.fabricmc.fabric.api.loot.v3.LootTableEvents.ModifyDrops.class);
    public static interface ModifyDrops {
        void modifyLootTableDrops(net.minecraft.core.Holder<net.minecraft.world.level.storage.loot.LootTable> p0, net.minecraft.world.level.storage.loot.LootContext p1, java.util.List<net.minecraft.world.item.ItemStack> p2);
    }
    public static interface Replace {
        net.minecraft.world.level.storage.loot.LootTable replaceLootTable(net.minecraft.resources.ResourceKey<net.minecraft.world.level.storage.loot.LootTable> p0, net.minecraft.world.level.storage.loot.LootTable p1, net.fabricmc.fabric.api.loot.v3.LootTableSource p2, net.minecraft.core.HolderLookup.Provider p3);
    }
    // End of what tools/kiln-stubs.py generated.
}
