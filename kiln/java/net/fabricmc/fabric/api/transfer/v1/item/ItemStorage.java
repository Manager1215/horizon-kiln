package net.fabricmc.fabric.api.transfer.v1.item;

import kiln.GameContainers;
import net.fabricmc.fabric.api.lookup.v1.block.BlockApiLookup;
import net.fabricmc.fabric.api.transfer.v1.storage.Storage;
import net.minecraft.core.Direction;
import net.minecraft.resources.Identifier;
import net.minecraft.world.Container;

/**
 * Kiln's stand-in for Fabric's {@code ItemStorage}: where a block keeps items, found by its lookup. As in Fabric, a
 * block entity that is a {@code Container} and that no mod gave a storage of its own is one through the face asked
 * ({@code ContainerStorage.of}): one machine's output reaches the next machine's input. The game's own containers (a
 * chest, a double chest, a barrel, a hopper, a furnace, a brewing stand, a composter...) aren't objects on Kiln's side:
 * {@code kiln.GameContainers} makes one of the game's slots for the call (D-144, D-199).
 */
public final class ItemStorage {
    public static final BlockApiLookup<Storage<ItemVariant>, Direction> SIDED = BlockApiLookup.get(
            Identifier.fromNamespaceAndPath("fabric", "sided_item_storage"), Storage.asClass(), Direction.class);

    static {
        SIDED.registerFallback((level, pos, state, entity, direction) -> {
            // The game's own first: a chest's block entity is one half, its storage the double chest.
            Container game = entity == null || GameContainers.isGame(entity) ? GameContainers.at(level, pos, state)
                    : null;
            if (game != null) {
                return ContainerStorage.of(game, direction);
            }
            return entity instanceof Container container ? ContainerStorage.of(container, direction) : null;
        });
    }

    private ItemStorage() {}
    // Generated by tools/kiln-stubs.py: what the mods use that isn't written by hand yet; names and signatures only.
    public static final net.fabricmc.fabric.api.lookup.v1.item.ItemApiLookup<net.fabricmc.fabric.api.transfer.v1.storage.Storage<net.fabricmc.fabric.api.transfer.v1.item.ItemVariant>, net.fabricmc.fabric.api.transfer.v1.context.ContainerItemContext> ITEM = null;
    // End of what tools/kiln-stubs.py generated.
}
