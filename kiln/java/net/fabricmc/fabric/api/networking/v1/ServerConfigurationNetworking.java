package net.fabricmc.fabric.api.networking.v1;

import java.util.Objects;
import kiln.Net;
import net.minecraft.network.protocol.Packet;
import net.minecraft.network.protocol.common.ClientCommonPacketListener;
import net.minecraft.network.protocol.common.custom.CustomPacketPayload;
import net.minecraft.server.MinecraftServer;
import net.minecraft.server.network.ServerConfigurationPacketListenerImpl;

/**
 * Kiln's stand-in for Fabric's {@code ServerConfigurationNetworking}: the configuration phase's payloads on the server
 * (D-199), carried over Kiln's channel as {@link Net} carries play's, marked as the configuration's. A receiver hears
 * what a player's window sends back while the server's configuration events run, or after (Kiln's configuration ends
 * when its events have run: a reply comes at the player's next tick).
 */
public final class ServerConfigurationNetworking {
    private ServerConfigurationNetworking() {}

    public static <T extends CustomPacketPayload> boolean registerGlobalReceiver(CustomPacketPayload.Type<T> type,
            ConfigurationPacketHandler<T> handler) {
        return Net.SERVER_CONFIGURATION_RECEIVERS.putIfAbsent(type.id(), handler) == null;
    }

    public static ConfigurationPacketHandler<?> unregisterGlobalReceiver(net.minecraft.resources.Identifier id) {
        return Net.SERVER_CONFIGURATION_RECEIVERS.remove(id);
    }

    /** Whether the player's window receives the type: Kiln's sides load the same mods, so any type registered. */
    public static boolean canSend(ServerConfigurationPacketListenerImpl handler, CustomPacketPayload.Type<?> type) {
        return Net.CLIENTBOUND_CONFIGURATION.has(type.id());
    }

    public static boolean canSend(ServerConfigurationPacketListenerImpl handler, net.minecraft.resources.Identifier id) {
        return Net.CLIENTBOUND_CONFIGURATION.has(id);
    }

    public static Packet<ClientCommonPacketListener> createClientboundPacket(CustomPacketPayload payload) {
        return new Net.ConfigurationPacket(Objects.requireNonNull(payload, "Payload cannot be null"));
    }

    public static void send(ServerConfigurationPacketListenerImpl handler, CustomPacketPayload payload) {
        Net.sendConfigurationToPlayer(handler.kiln$player(), payload);
    }

    public static PacketSender getSender(ServerConfigurationPacketListenerImpl handler) {
        return new PacketSender() {
            @Override
            public void sendPacket(CustomPacketPayload payload) {
                send(handler, payload);
            }
        };
    }

    @FunctionalInterface
    public interface ConfigurationPacketHandler<T extends CustomPacketPayload> {
        void receive(T payload, Context context);
    }

    public interface Context {
        MinecraftServer server();

        ServerConfigurationPacketListenerImpl networkHandler();

        PacketSender responseSender();
        // Generated by tools/kiln-stubs.py: what the mods use that isn't written by hand yet; names and signatures only.
        default net.minecraft.server.network.ServerConfigurationPacketListenerImpl packetListener() { kiln.Missing.called("net.fabricmc.fabric.api.networking.v1.ServerConfigurationNetworking.Context.packetListener"); return null; }
        // End of what tools/kiln-stubs.py generated.
    }
}
