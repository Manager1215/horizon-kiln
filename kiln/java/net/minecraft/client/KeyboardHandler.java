package net.minecraft.client;

import net.fabricmc.fabric.api.client.screen.v1.ScreenKeyboardEvents;
import net.minecraft.client.gui.screens.Screen;

/**
 * Kiln's stand-in for {@code KeyboardHandler}: the keyboard as the game handles it. Horizon handles the keys; the mods'
 * mixins in {@link #keyPress} run at Horizon's {@code key} hook (Kiln's Mixin bridge, D-102).
 */
public class KeyboardHandler {
    private final Minecraft minecraft;

    public KeyboardHandler(Minecraft minecraft) {
        this.minecraft = minecraft;
    }

    protected KeyboardHandler() {
        this(Minecraft.getInstance());
    }

    /**
     * A key went down (action 1) or up (0). Over a screen Kiln hands the mods ({@link #kiln$key}), the screen's
     * {@code keyPressed} or {@code keyReleased} with Fabric's events, as vanilla's (D-215: Architectury wraps those
     * calls); while playing, Horizon's key hook (D-102).
     */
    public void keyPress(long window, int action, net.minecraft.client.input.KeyEvent event) {
        Screen screen = kiln$screen;
        if (screen == null) {
            kiln.Bridge.body(null, window, action, event);
            return;
        }
        if (action != 0) {
            if (ScreenKeyboardEvents.allowKeyPress(screen).invoker().allowKeyPress(screen, event)) {
                ScreenKeyboardEvents.beforeKeyPress(screen).invoker().beforeKeyPress(screen, event);
                // Escape over the game's own container screen is the game's: it closes its window (D-156).
                if (!(kiln$gamesEscape && event.isEscape())) {
                    screen.keyPressed(event);
                }
                ScreenKeyboardEvents.afterKeyPress(screen).invoker().afterKeyPress(screen, event);
            }
        } else if (ScreenKeyboardEvents.allowKeyRelease(screen).invoker().allowKeyRelease(screen, event)) {
            ScreenKeyboardEvents.beforeKeyRelease(screen).invoker().beforeKeyRelease(screen, event);
            screen.keyReleased(event);
            ScreenKeyboardEvents.afterKeyRelease(screen).invoker().afterKeyRelease(screen, event);
        }
    }

    /** Kiln's own: the screen a key is being handed to now, or null (Horizon's hook while playing). */
    private Screen kiln$screen;
    private boolean kiln$gamesEscape;

    /**
     * Kiln's own: a key down ({@code press}) or up over {@code screen}, as vanilla's {@link #keyPress} gives it;
     * {@code gamesEscape}: Escape is the game's.
     */
    public void kiln$key(Screen screen, net.minecraft.client.input.KeyEvent event, boolean press, boolean gamesEscape) {
        kiln$screen = screen;
        kiln$gamesEscape = gamesEscape;
        try {
            keyPress(0L, press ? 1 : 0, event);
        } finally {
            kiln$screen = null;
        }
    }

    private static volatile String clipboard = "";

    /**
     * The system's clipboard, as the game last read it for Kiln: with each paste key over a mod's text field (Control+V,
     * on macOS Command+V), and what a mod copied since (D-174). Empty when it holds no text.
     */
    public String getClipboard() {
        return clipboard;
    }

    /** Text onto the system's clipboard, through the game's own; empty text is not copied, as vanilla's. */
    public void setClipboard(String text) {
        if (text == null || text.isEmpty()) {
            return;
        }
        clipboard = text;
        kiln.Screens.copied(text);
    }

    /** Kiln's own: the clipboard's text, as the game read it. */
    public static void kiln$clipboard(String text) {
        clipboard = text == null ? "" : text;
    }
    // Generated by tools/kiln-stubs.py: what the mods use that isn't written by hand yet; names and signatures only.
    public void tick() { kiln.Missing.called("net.minecraft.client.KeyboardHandler.tick"); }
    // End of what tools/kiln-stubs.py generated.
}
