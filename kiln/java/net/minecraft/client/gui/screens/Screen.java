package net.minecraft.client.gui.screens;

import net.minecraft.client.Minecraft;
import net.minecraft.client.gui.Font;
import net.minecraft.network.chat.Component;

/**
 * Kiln's stand-in for {@code Screen}: a screen of the window's game (the game draws its own) or a mod's, which loads
 * but Kiln doesn't show yet ({@link net.minecraft.client.gui.Gui#setScreen}).
 */
public abstract class Screen {
    protected final Component title;
    protected final Minecraft minecraft;
    protected final Font font;
    /** Its size in GUI pixels, from its init. */
    public int width;
    public int height;

    protected Screen(Component title) {
        this(Minecraft.getInstance(), Minecraft.getInstance().font, title);
    }

    protected Screen(Minecraft minecraft, Font font, Component title) {
        this.title = title;
        this.minecraft = minecraft;
        this.font = font;
    }

    public Component getTitle() {
        return title;
    }

    /** It opens, or the window changed size: its size, then its own {@link #init()}. */
    public final void init(int width, int height) {
        this.width = width;
        this.height = height;
        init();
    }

    protected void init() {}

    /** A client tick while it is open. */
    public void tick() {}

    /** It became the screen on top. */
    public void added() {}

    /** It is no longer the screen on top. */
    public void removed() {}

    /** Whether the game pauses under it in single player. */
    public boolean isPauseScreen() {
        return true;
    }

    public void onClose() {}
    // Generated by tools/kiln-stubs.py: what the mods use that isn't written by hand yet; names and signatures only.
    public java.util.List<net.minecraft.client.gui.narration.NarratableEntry> narratables;
    public void extractRenderState(net.minecraft.client.gui.GuiGraphicsExtractor p0, int p1, int p2, float p3) { kiln.Missing.called("net.minecraft.client.gui.screens.Screen.extractRenderState"); }
    public boolean keyPressed(net.minecraft.client.input.KeyEvent p0) { kiln.Missing.called("net.minecraft.client.gui.screens.Screen.keyPressed"); return false; }
    protected <T extends net.minecraft.client.gui.components.Renderable> T addRenderableOnly(T p0) { kiln.Missing.called("net.minecraft.client.gui.screens.Screen.addRenderableOnly"); return null; }
    public void extractBackground(net.minecraft.client.gui.GuiGraphicsExtractor p0, int p1, int p2, float p3) { kiln.Missing.called("net.minecraft.client.gui.screens.Screen.extractBackground"); }
    // End of what tools/kiln-stubs.py generated.
}
