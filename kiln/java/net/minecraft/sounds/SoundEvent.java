package net.minecraft.sounds;

import java.util.Optional;
import net.minecraft.resources.Identifier;

/** Kiln's stand-in for {@code SoundEvent}: a sound by its id, which Horizon plays. */
public record SoundEvent(Identifier location, Optional<Float> fixedRange) {
    public static SoundEvent createVariableRangeEvent(Identifier location) {
        return new SoundEvent(location, Optional.empty());
    }

    public static SoundEvent createFixedRangeEvent(Identifier location, float range) {
        return new SoundEvent(location, Optional.of(range));
    }

    public float getRange(float volume) {
        return fixedRange.orElse(volume > 1.0F ? 16.0F * volume : 16.0F);
    }
    // Generated by tools/kiln-stubs.py: what the mods use that isn't written by hand yet; names and signatures only.
    public static final com.mojang.serialization.Codec<net.minecraft.sounds.SoundEvent> DIRECT_CODEC = kiln.Constants.codec("net.minecraft.sounds.SoundEvent.DIRECT_CODEC");
    public static final com.mojang.serialization.Codec<net.minecraft.core.Holder<net.minecraft.sounds.SoundEvent>> CODEC = kiln.Constants.codec("net.minecraft.sounds.SoundEvent.CODEC");
    public static final net.minecraft.network.codec.StreamCodec<net.minecraft.network.RegistryFriendlyByteBuf, net.minecraft.core.Holder<net.minecraft.sounds.SoundEvent>> STREAM_CODEC = kiln.Constants.streamCodec("net.minecraft.sounds.SoundEvent.STREAM_CODEC");
    // End of what tools/kiln-stubs.py generated.
}
