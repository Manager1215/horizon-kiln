    /**
     * A profile's properties: saved as a list of {@code name}, {@code value} and {@code signature}; read from that or
     * from a map of each name to its values (unsigned).
     */
    public static final Codec<PropertyMap> PROPERTY_MAP = Codec.either(
            Codec.unboundedMap(Codec.STRING, Codec.STRING.listOf()), PROPERTY.listOf())
            .xmap(either -> {
                ImmutableMultimap.Builder<String, Property> properties = ImmutableMultimap.builder();
                either.ifLeft(map -> map.forEach((name, values) -> values.forEach(
                        value -> properties.put(name, new Property(name, value)))))
                        .ifRight(list -> list.forEach(p -> properties.put(p.name(), p)));
                return new PropertyMap(properties.build());
            }, map -> Either.<Map<String, List<String>>, List<Property>>right(List.copyOf(map.values())));
    /** A player's name: at most 16 characters, none of them a space or a control character. */
    public static final Codec<String> PLAYER_NAME = Codec.string(0, 16).validate(name -> StringUtil.isValidPlayerName(name)
            ? DataResult.success(name)
            : DataResult.error(() -> "Player name contained disallowed characters: '" + name + "'"));
    /** A whole profile as the game saves it: its id, its name and its properties. */
    public static final MapCodec<GameProfile> STORED_GAME_PROFILE = RecordCodecBuilder.mapCodec(i -> i.group(
            UUIDUtil.CODEC.fieldOf("id").forGetter(GameProfile::id),
            PLAYER_NAME.fieldOf("name").forGetter(GameProfile::name),
            PROPERTY_MAP.optionalFieldOf("properties", PropertyMap.EMPTY).forGetter(GameProfile::properties))
            .apply(i, GameProfile::new));

    public ExtraCodecs() {}

    private static Codec<Integer> intAbove(int bound) {
        return Codec.INT.validate(value -> value > bound ? DataResult.success(value)
                : DataResult.error(() -> "Value must be above " + bound + ": " + value));
    }

    /** Ids and values a codec maps between, filled after it is made (as registries are). */
    public static class LateBoundIdMapper<I, V> {
        private final Map<I, V> byId = new HashMap<>();
        private final Map<V, I> byValue = new HashMap<>();

        public LateBoundIdMapper() {}

        public LateBoundIdMapper<I, V> put(I id, V value) {
            byId.put(id, value);
            byValue.put(value, id);
            return this;
        }

        public Codec<V> codec(Codec<I> ids) {
            return ids.comapFlatMap(id -> byId.containsKey(id) ? DataResult.success(byId.get(id))
                    : DataResult.error(() -> "unknown " + id), byValue::get);
        }
    }
