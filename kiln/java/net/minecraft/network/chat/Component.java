package net.minecraft.network.chat;

import com.google.gson.JsonObject;

/**
 * Kiln's stand-in for {@code Component}: chat text, literal or translated, with a colour and styles. Horizon gets it
 * as vanilla's JSON ({@link #kiln$json}) and shows it in the player's language; {@link #getString} is English.
 */
public interface Component extends FormattedText, com.mojang.brigadier.Message {
    /** The text as the player reads it (in English, from the mods' own language files). */
    @Override
    String getString();

    /** Its text as one piece. */
    @Override
    default <T> java.util.Optional<T> visit(FormattedText.ContentConsumer<T> consumer) {
        return consumer.accept(getString());
    }

    /** Kiln's own: the text as vanilla's JSON form, {@code {"translate":"...","color":"dark_red"}}. */
    JsonObject kiln$json();

    static MutableComponent literal(String text) {
        return MutableComponent.kiln$literal(text);
    }

    static MutableComponent translatable(String key) {
        return MutableComponent.kiln$translatable(key, new Object[0]);
    }

    static MutableComponent translatable(String key, Object... args) {
        return MutableComponent.kiln$translatable(key, args);
    }

    /** A translation, or the fallback text when no language has the key (D-170: Mezz Config GUI's labels). */
    static MutableComponent translatableWithFallback(String key, String fallback) {
        return kiln.Language.has(key) ? translatable(key) : literal(fallback == null ? key : fallback);
    }

    static MutableComponent translatableWithFallback(String key, String fallback, Object... args) {
        return kiln.Language.has(key) ? translatable(key, args) : literal(fallback == null ? key : fallback);
    }

    static MutableComponent empty() {
        return MutableComponent.kiln$literal("");
    }
    /** What it holds before its style and siblings: a literal text or a translation. */
    default ComponentContents getContents() {
        return net.minecraft.network.chat.contents.PlainTextContents.create(getString());
    }

    /** Its style; a literal's or a translation's own, plain unless set. */
    default Style getStyle() {
        return Style.EMPTY;
    }

    /** A new component with its contents and style, that can be changed without changing this one. */
    default MutableComponent copy() {
        return MutableComponent.create(getContents()).setStyle(getStyle());
    }

    /** The components after its own text; none for a plain one. */
    default java.util.List<Component> getSiblings() {
        return java.util.List.of();
    }

    /** Its text and its siblings', without its style. */
    default MutableComponent plainCopy() {
        return MutableComponent.create(getContents());
    }

    /** It laid out to draw, each piece in its style. */
    default net.minecraft.util.FormattedCharSequence getVisualOrderText() {
        return net.minecraft.locale.Language.getInstance().getVisualOrder(this);
    }

    /** {@code text} as a plain component, an empty one for none (Just Enough Breeding's mob names, D-173). */
    static Component nullToEmpty(String text) {
        return text != null ? literal(text) : empty();
    }

    /** Its text, cut to {@code length} characters at most. */
    default String getString(int length) {
        String text = getString();
        return text.length() <= length ? text : text.substring(0, length);
    }
    // Generated by tools/kiln-stubs.py: what the mods use that isn't written by hand yet; names and signatures only.
    // End of what tools/kiln-stubs.py generated.
}
