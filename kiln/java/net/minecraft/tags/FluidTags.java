package net.minecraft.tags;

import net.minecraft.core.registries.Registries;
import net.minecraft.resources.Identifier;
import net.minecraft.world.level.material.Fluid;

/** Kiln's stand-in for {@code FluidTags}: the game's two fluid tags, by their ids. */
public final class FluidTags {
    public static final TagKey<Fluid> WATER = create("water");
    public static final TagKey<Fluid> LAVA = create("lava");

    private FluidTags() {}

    private static TagKey<Fluid> create(String name) {
        return TagKey.create(Registries.FLUID, Identifier.withDefaultNamespace(name));
    }
    // Generated by tools/kiln-stubs.py: what the mods use that isn't written by hand yet; names and signatures only.
    public static final net.minecraft.tags.TagKey<net.minecraft.world.level.material.Fluid> SUPPORTS_LILY_PAD = create("supports_lily_pad");
    // End of what tools/kiln-stubs.py generated.
}
