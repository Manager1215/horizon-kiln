    /** What a walk over positions does at one ({@link #breadthFirstTraversal}). */
    public enum TraversalNodeStatus {
        /** Count it and go on to its neighbours. */
        ACCEPT,
        /** Neither count it nor go past it. */
        SKIP,
        /** End the walk. */
        STOP
    }

    /**
     * Walks out from {@code start}, nearest first, at most {@code maxDepth} steps away: each position {@code
     * neighbours} gives is visited once, and only past positions {@code visit} accepts. Ends when {@code maxCount}
     * were accepted ({@code start} among them) or {@code visit} says stop; returns how many were.
     */
    public static int breadthFirstTraversal(BlockPos start, int maxDepth, int maxCount,
            java.util.function.BiConsumer<BlockPos, java.util.function.Consumer<BlockPos>> neighbours,
            java.util.function.Function<BlockPos, TraversalNodeStatus> visit) {
        java.util.ArrayDeque<BlockPos> queue = new java.util.ArrayDeque<>();
        java.util.Map<BlockPos, Integer> depth = new java.util.HashMap<>();
        queue.add(start.immutable());
        depth.put(start.immutable(), 0);
        int accepted = 0;
        while (!queue.isEmpty()) {
            BlockPos pos = queue.poll();
            TraversalNodeStatus status = visit.apply(pos);
            if (status == TraversalNodeStatus.STOP) {
                break;
            }
            if (status != TraversalNodeStatus.ACCEPT) {
                continue;
            }
            if (++accepted >= maxCount) {
                break;
            }
            int steps = depth.get(pos);
            if (steps < maxDepth) {
                neighbours.accept(pos, next -> {
                    BlockPos at = next.immutable();
                    if (depth.putIfAbsent(at, steps + 1) == null) {
                        queue.add(at);
                    }
                });
            }
        }
        return accepted;
    }

