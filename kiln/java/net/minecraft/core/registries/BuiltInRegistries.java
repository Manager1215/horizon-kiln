package net.minecraft.core.registries;

import net.minecraft.core.DefaultedMappedRegistry;
import net.minecraft.core.DefaultedRegistry;
import net.minecraft.core.MappedRegistry;
import net.minecraft.core.Registry;
import net.minecraft.resources.Identifier;
import net.minecraft.resources.ResourceKey;
import net.minecraft.core.component.DataComponentType;
import net.minecraft.sounds.SoundEvent;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.Items;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.entity.BlockEntityType;

/**
 * Kiln's stand-in for {@code BuiltInRegistries}: what the Java mods register. A mod's item meets Horizon's import of
 * the mod's data by its id: Kiln runs the item's code when a player uses Horizon's item of that id.
 */
public final class BuiltInRegistries {
    public static final DefaultedRegistry<Block> BLOCK = new DefaultedMappedRegistry<>("minecraft:air", Registries.BLOCK);
    public static final DefaultedRegistry<Item> ITEM = new DefaultedMappedRegistry<>("minecraft:air", Registries.ITEM);
    public static final Registry<SoundEvent> SOUND_EVENT = new MappedRegistry<>(Registries.SOUND_EVENT);
    public static final Registry<BlockEntityType<?>> BLOCK_ENTITY_TYPE = new MappedRegistry<>(Registries.BLOCK_ENTITY_TYPE);
    public static final DefaultedRegistry<net.minecraft.world.level.material.Fluid> FLUID = defaulted("fluid");
    public static final Registry<DataComponentType<?>> DATA_COMPONENT_TYPE =
            new MappedRegistry<>(Registries.DATA_COMPONENT_TYPE);
    public static final Registry<net.minecraft.world.item.crafting.RecipeType<?>> RECIPE_TYPE =
            new MappedRegistry<>(Registries.RECIPE_TYPE);
    public static final DefaultedRegistry<net.minecraft.world.entity.EntityType<?>> ENTITY_TYPE = defaulted("entity_type");
    public static final Registry<net.minecraft.core.particles.ParticleType<?>> PARTICLE_TYPE = registry("particle_type");
    public static final Registry<net.minecraft.world.effect.MobEffect> MOB_EFFECT = registry("mob_effect");

    static {
        // Vanilla's Bootstrap fills the registries before any mod runs: the game's blocks and items Kiln names are in
        // them too.
        // Started from Items itself, this returns at once (its class is being made on this thread). The fluids come
        // before the items: the game's buckets hold them.
        try {
            Class.forName(Blocks.class.getName());
            Class.forName(net.minecraft.world.level.material.Fluids.class.getName());
            Class.forName(Items.class.getName());
            Class.forName(net.minecraft.world.entity.EntityType.class.getName());
            Class.forName(net.minecraft.core.particles.ParticleTypes.class.getName());
            Class.forName(net.minecraft.world.effect.MobEffects.class.getName());
        } catch (ClassNotFoundException e) {
            throw new IllegalStateException(e);
        }
    }

    private BuiltInRegistries() {}

    /** Kiln's own: the registries a generated stand-in names (below), empty until the mods register in them. */
    private static <T> Registry<T> registry(String name) {
        return new MappedRegistry<>(ResourceKey.createRegistryKey(Identifier.withDefaultNamespace(name)));
    }

    private static <T> DefaultedRegistry<T> defaulted(String name) {
        String fallback = switch (name) {
            case "fluid" -> "minecraft:empty";
            case "entity_type" -> "minecraft:pig";
            default -> "minecraft:air";
        };
        return new DefaultedMappedRegistry<>(fallback, ResourceKey.createRegistryKey(Identifier.withDefaultNamespace(name)));
    }
    // Generated by tools/kiln-stubs.py: what the mods use that isn't written by hand yet; names and signatures only.
    public static final net.minecraft.core.Registry<net.minecraft.world.inventory.MenuType<?>> MENU = registry("menu");
    public static final net.minecraft.core.Registry<net.minecraft.world.item.crafting.RecipeSerializer<?>> RECIPE_SERIALIZER = registry("recipe_serializer");
    public static final net.minecraft.core.Registry<net.minecraft.world.level.levelgen.feature.treedecorators.TreeDecoratorType<?>> TREE_DECORATOR_TYPE = registry("tree_decorator_type");
    public static final net.minecraft.core.Registry<net.minecraft.world.item.CreativeModeTab> CREATIVE_MODE_TAB = registry("creative_mode_tab");
    // End of what tools/kiln-stubs.py generated.
}
