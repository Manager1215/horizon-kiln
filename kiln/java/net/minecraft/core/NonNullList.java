package net.minecraft.core;

import java.util.AbstractList;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.Objects;

/** Kiln's stand-in for {@code NonNullList}: a list without nulls, of a fixed size when made with a default. */
public class NonNullList<E> extends AbstractList<E> {
    private final List<E> list;
    private final E defaultValue;

    protected NonNullList(List<E> list, E defaultValue) {
        this.list = list;
        this.defaultValue = defaultValue;
    }

    public static <E> NonNullList<E> create() {
        return new NonNullList<>(new ArrayList<>(), null);
    }

    public static <E> NonNullList<E> createWithCapacity(int capacity) {
        return new NonNullList<>(new ArrayList<>(capacity), null);
    }

    public static <E> NonNullList<E> withSize(int size, E defaultValue) {
        Objects.requireNonNull(defaultValue);
        Object[] values = new Object[size];
        Arrays.fill(values, defaultValue);
        @SuppressWarnings("unchecked")
        List<E> list = (List<E>) Arrays.asList(values);
        return new NonNullList<>(list, defaultValue);
    }

    @SafeVarargs
    public static <E> NonNullList<E> of(E defaultValue, E... values) {
        return new NonNullList<>(Arrays.asList(values), defaultValue);
    }

    @Override
    public E get(int index) {
        return list.get(index);
    }

    @Override
    public E set(int index, E value) {
        return list.set(index, Objects.requireNonNull(value));
    }

    @Override
    public void add(int index, E value) {
        list.add(index, Objects.requireNonNull(value));
    }

    @Override
    public E remove(int index) {
        return list.remove(index);
    }

    @Override
    public int size() {
        return list.size();
    }

    @Override
    public void clear() {
        if (defaultValue == null) {
            super.clear();
        } else {
            for (int i = 0; i < size(); i++) {
                set(i, defaultValue);
            }
        }
    }
    // Generated by tools/kiln-stubs.py: what the mods use that isn't written by hand yet; names and signatures only.
    // End of what tools/kiln-stubs.py generated.
}
