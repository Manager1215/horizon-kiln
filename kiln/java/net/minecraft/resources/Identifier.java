    public static Identifier fromNamespaceAndPath(String namespace, String path) {
        return new Identifier(namespace, path);
    }

    /** {@code namespace:path}, or {@code path} in the {@code minecraft} namespace. */
    public static Identifier parse(String id) {
        int colon = id.indexOf(':');
        return colon < 0 ? withDefaultNamespace(id) : new Identifier(id.substring(0, colon), id.substring(colon + 1));
    }

    /**
     * {@code id} as {@code parse} reads it, or null when it isn't one: a namespace of lowercase letters, digits and
     * {@code _-.}, a path of those and {@code /}.
     */
    public static Identifier tryParse(String id) {
        int colon = id.indexOf(':');
        String namespace = colon < 0 ? "minecraft" : id.substring(0, colon);
        String path = id.substring(colon + 1);
        boolean valid = !namespace.isEmpty() && !path.isEmpty() && namespace.chars().allMatch(c -> allowed(c, false))
                && path.chars().allMatch(c -> allowed(c, true));
        return valid ? new Identifier(namespace, path) : null;
    }

    /** {@code namespace:path}, or null when either isn't one (the characters {@link #tryParse} allows). */
    public static Identifier tryBuild(String namespace, String path) {
        boolean valid = !namespace.isEmpty() && !path.isEmpty() && namespace.chars().allMatch(c -> allowed(c, false))
                && path.chars().allMatch(c -> allowed(c, true));
        return valid ? new Identifier(namespace, path) : null;
    }

    private static boolean allowed(int c, boolean slash) {
        return c >= 'a' && c <= 'z' || c >= '0' && c <= '9' || c == '_' || c == '-' || c == '.' || slash && c == '/';
    }

    public static Identifier withDefaultNamespace(String path) {
        return new Identifier("minecraft", path);
    }

    /** Whether {@code c} may be in a path: a-z, 0-9, _ - . and /. */
    public static boolean validPathChar(char c) {
        return allowed(c, true);
    }

    /** Whether {@code c} may be in a namespace: a-z, 0-9, _ - and . */
    public static boolean validNamespaceChar(char c) {
        return allowed(c, false);
    }

    public static boolean isValidPath(String path) {
        return path.chars().allMatch(c -> allowed(c, true));
    }

    public static boolean isValidNamespace(String namespace) {
        return namespace.chars().allMatch(c -> allowed(c, false));
    }

    public Identifier withPath(String path) {
        return fromNamespaceAndPath(namespace, path);
    }

    public Identifier withPath(java.util.function.UnaryOperator<String> path) {
        return withPath(path.apply(this.path));
    }

    public Identifier withPrefix(String prefix) {
        return withPath(prefix + path);
    }

    public Identifier withSuffix(String suffix) {
        return withPath(path + suffix);
    }

    public String toLanguageKey() {
        return namespace + "." + path;
    }

    public String toLanguageKey(String type) {
        return type + "." + toLanguageKey();
    }

    public String getPath() {
        return path;
    }

    public String getNamespace() {
        return namespace;
    }

    @Override
    public String toString() {
        return namespace + ":" + path;
    }

    @Override
    public boolean equals(Object o) {
        return o instanceof Identifier i && i.namespace.equals(namespace) && i.path.equals(path);
    }

    @Override
    public int hashCode() {
        return Objects.hash(namespace, path);
    }

    @Override
    public int compareTo(Identifier o) {
        int c = path.compareTo(o.path);
        return c != 0 ? c : namespace.compareTo(o.namespace);
    }
