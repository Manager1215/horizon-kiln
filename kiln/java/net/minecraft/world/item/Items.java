    private static Item register(String name) {
        Identifier id = Identifier.withDefaultNamespace(name);
        return Registry.register(BuiltInRegistries.ITEM, id,
                new Item(new Item.Properties().setId(ResourceKey.create(Registries.ITEM, id))));
    }

    /** A bucket of {@code fluid}, which Fabric's {@code FluidStorage} empties into a mod's tank. */
    private static Item bucket(String name, Fluid fluid) {
        Identifier id = Identifier.withDefaultNamespace(name);
        return Registry.register(BuiltInRegistries.ITEM, id,
                new BucketItem(fluid, new Item.Properties().setId(ResourceKey.create(Registries.ITEM, id)).stacksTo(1)));
    }
