    private static Item register(String name) {
        Identifier id = Identifier.withDefaultNamespace(name);
        return Registry.register(BuiltInRegistries.ITEM, id,
                Item.kiln$game(id, new Item.Properties().setId(ResourceKey.create(Registries.ITEM, id))));
    }

    /** The game's sixteen items {@code <colour>_<suffix>}, in DyeColor's order. */
    private static net.minecraft.world.level.block.ColorCollection<Item> colors(String suffix) {
        return net.minecraft.world.level.block.ColorCollection.kiln$of(color -> game(color + "_" + suffix));
    }

    /** The game's item {@code name}: the one the registry holds, else made as the game makes it (D-159). */
    private static Item game(String name) {
        return Item.kiln$byId("minecraft:" + name);
    }

    /** A bucket of {@code fluid}, which Fabric's {@code FluidStorage} empties into a mod's tank. */
    private static Item bucket(String name, Fluid fluid) {
        Identifier id = Identifier.withDefaultNamespace(name);
        return Registry.register(BuiltInRegistries.ITEM, id,
                new BucketItem(fluid, new Item.Properties().setId(ResourceKey.create(Registries.ITEM, id)).stacksTo(1)));
    }
