package net.minecraft.world.item.crafting;

import com.mojang.serialization.MapCodec;
import net.minecraft.network.RegistryFriendlyByteBuf;
import net.minecraft.network.codec.StreamCodec;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.ItemStackTemplate;
import net.minecraft.world.level.Level;

/**
 * Kiln's stand-in for {@code BookCloningRecipe} ({@code minecraft:crafting_special_bookcloning}): a written book of an
 * allowed generation (an original or a copy of one: 0 to 1) and book and quills make copies of it, one generation on;
 * the book stays in the grid, as in the game (D-197).
 */
public class BookCloningRecipe extends CustomRecipe {
    public static final MapCodec<BookCloningRecipe> MAP_CODEC =
            kiln.Constants.mapCodec("net.minecraft.world.item.crafting.BookCloningRecipe.MAP_CODEC");
    public static final StreamCodec<RegistryFriendlyByteBuf, BookCloningRecipe> STREAM_CODEC =
            kiln.Constants.streamCodec("net.minecraft.world.item.crafting.BookCloningRecipe.STREAM_CODEC");
    public static final RecipeSerializer<BookCloningRecipe> SERIALIZER = new RecipeSerializer<>(MAP_CODEC, STREAM_CODEC);

    public final Ingredient source;
    public final Ingredient material;
    public final ItemStackTemplate result;

    /** The game's default: an original and a copy of an original can be copied, a copy of a copy can't. */
    public static final net.minecraft.advancements.predicates.MinMaxBounds.Ints DEFAULT_GENERATIONS =
            net.minecraft.advancements.predicates.MinMaxBounds.Ints.between(0, 1);
    public final net.minecraft.advancements.predicates.MinMaxBounds.Ints allowedGenerations;

    public BookCloningRecipe(Ingredient source, Ingredient material,
            net.minecraft.advancements.predicates.MinMaxBounds.Ints allowedGenerations, ItemStackTemplate result) {
        this.source = source;
        this.material = material;
        this.allowedGenerations = allowedGenerations;
        this.result = result;
    }

    @Override
    public boolean matches(CraftingInput input, Level level) {
        ItemStack book = ItemStack.EMPTY;
        int copies = 0;
        for (ItemStack stack : input.items()) {
            if (stack.isEmpty()) {
                continue;
            }
            if (source.test(stack)) {
                if (!book.isEmpty()) {
                    return false;
                }
                book = stack;
            } else if (material.test(stack)) {
                copies++;
            } else {
                return false;
            }
        }
        return !book.isEmpty() && copies > 0 && generation(book) >= 0
                && allowedGenerations.matches(generation(book));
    }

    /** Kiln's own: a written book's generation as saved, -1 when it has no content. */
    private static int generation(ItemStack book) {
        net.minecraft.world.item.component.WrittenBookContent content =
                book.get(net.minecraft.core.component.DataComponents.WRITTEN_BOOK_CONTENT);
        return content == null ? -1 : content.generation();
    }

    @Override
    public ItemStack assemble(CraftingInput input) {
        ItemStack book = kiln$first(input, source);
        net.minecraft.world.item.component.WrittenBookContent content =
                book.get(net.minecraft.core.component.DataComponents.WRITTEN_BOOK_CONTENT);
        if (book.isEmpty() || content == null) {
            return ItemStack.EMPTY;
        }
        net.minecraft.world.item.component.WrittenBookContent copied = new net.minecraft.world.item.component
                .WrittenBookContent(content.title(), content.author(), content.generation() + 1, content.pages(),
                content.resolved());
        ItemStack copy = result.apply(book.getComponentsPatch()).copyWithCount(kiln$count(input, material));
        copy.set(net.minecraft.core.component.DataComponents.WRITTEN_BOOK_CONTENT, copied);
        return copy;
    }

    /** The book copied stays in the grid. */
    @Override
    public net.minecraft.core.NonNullList<ItemStack> getRemainingItems(CraftingInput input) {
        net.minecraft.core.NonNullList<ItemStack> left = super.getRemainingItems(input);
        for (int i = 0; i < input.size(); i++) {
            ItemStack stack = input.getItem(i);
            if (!stack.isEmpty() && source.test(stack)) {
                left.set(i, stack.copyWithCount(1));
                break;
            }
        }
        return left;
    }

    @Override
    public RecipeSerializer<BookCloningRecipe> getSerializer() {
        return SERIALIZER;
    }
    // Generated by tools/kiln-stubs.py: what the mods use that isn't written by hand yet; names and signatures only.
    public static final net.minecraft.advancements.predicates.MinMaxBounds.Ints DEFAULT_BOOK_GENERATION_RANGES = new net.minecraft.advancements.predicates.MinMaxBounds.Ints((net.minecraft.advancements.predicates.MinMaxBounds.Bounds) null, (net.minecraft.advancements.predicates.MinMaxBounds.Bounds) null);
    // End of what tools/kiln-stubs.py generated.
}
