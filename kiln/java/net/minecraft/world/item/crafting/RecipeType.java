package net.minecraft.world.item.crafting;

import net.minecraft.core.Registry;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.Identifier;

/**
 * Kiln's stand-in for {@code RecipeType}: a kind of recipe, registered by its id ({@code minecraft:smelting}, a mod's
 * own). Kiln asks the game for recipes of the cooking kinds ({@link RecipeManager}).
 */
public interface RecipeType<T extends Recipe<?>> {
    RecipeType<SmeltingRecipe> SMELTING = register("smelting");
    RecipeType<BlastingRecipe> BLASTING = register("blasting");
    RecipeType<SmokingRecipe> SMOKING = register("smoking");
    RecipeType<CampfireCookingRecipe> CAMPFIRE_COOKING = register("campfire_cooking");

    static <T extends Recipe<?>> RecipeType<T> register(String name) {
        return Registry.register(BuiltInRegistries.RECIPE_TYPE, Identifier.withDefaultNamespace(name), new RecipeType<T>() {
            @Override
            public String toString() {
                return name;
            }
        });
    }
    // Generated by tools/kiln-stubs.py: what the mods use that isn't written by hand yet; names and signatures only.
    public static final net.minecraft.world.item.crafting.RecipeType<net.minecraft.world.item.crafting.CraftingRecipe> CRAFTING = register("crafting");
    // End of what tools/kiln-stubs.py generated.
}
