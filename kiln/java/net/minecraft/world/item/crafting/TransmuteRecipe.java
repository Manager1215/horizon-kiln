package net.minecraft.world.item.crafting;

import java.util.List;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.ItemStackTemplate;
import net.minecraft.world.item.Items;
import net.minecraft.world.item.crafting.display.RecipeDisplay;
import net.minecraft.world.item.crafting.display.ShapelessCraftingRecipeDisplay;
import net.minecraft.world.item.crafting.display.SlotDisplay;

/**
 * Kiln's stand-in for {@code TransmuteRecipe}: a crafting recipe that turns its input into another item with a
 * material (a bundle dyed), keeping the input's components; with a count of materials (a map cloned onto one to eight
 * empty ones) and the materials added to the result's count, as the game's (D-197).
 */
public class TransmuteRecipe extends NormalCraftingRecipe {
    public static final RecipeSerializer<TransmuteRecipe> SERIALIZER = new RecipeSerializer<>(
            kiln.Constants.mapCodec("net.minecraft.world.item.crafting.TransmuteRecipe.SERIALIZER"),
            kiln.Constants.streamCodec("net.minecraft.world.item.crafting.TransmuteRecipe.SERIALIZER"));

    public final Ingredient input;
    public final Ingredient material;
    /** As in the game: another item, or (without one, {@code map_cloning}'s {@code {}}) the input's own. */
    public final TransmuteResult result;

    /** How many materials it takes ({@code material_count}, one by default). */
    public final net.minecraft.advancements.predicates.MinMaxBounds.Ints materialCount;
    /** Whether the materials add to the result's count ({@code map_cloning}: a map and three empty ones make four). */
    public final boolean addMaterialCountToResult;

    public TransmuteRecipe(Recipe.CommonInfo commonInfo, CraftingRecipe.CraftingBookInfo bookInfo, Ingredient input,
            Ingredient material, net.minecraft.advancements.predicates.MinMaxBounds.Ints materialCount,
            TransmuteResult result, boolean addMaterialCountToResult) {
        super(commonInfo, bookInfo);
        this.input = input;
        this.material = material;
        this.materialCount = materialCount;
        this.result = result;
        this.addMaterialCountToResult = addMaterialCountToResult;
    }

    /** {@code result}'s item with {@code input}'s components, as the recipe makes it. */
    public static ItemStack createWithOriginalComponents(ItemStackTemplate result, ItemStack input) {
        return result.apply(input.getComponentsPatch());
    }

    /** The same, {@code count} of it. */
    public static ItemStack createWithOriginalComponents(ItemStackTemplate result, ItemStack input, int count) {
        return result.apply(input.getComponentsPatch()).copyWithCount(count);
    }

    @Override
    public RecipeSerializer<TransmuteRecipe> getSerializer() {
        return SERIALIZER;
    }

    @Override
    public boolean matches(CraftingInput input, net.minecraft.world.level.Level level) {
        int inputs = 0;
        int materials = 0;
        for (ItemStack stack : input.items()) {
            if (stack.isEmpty()) {
                continue;
            }
            if (this.input.test(stack) && inputs == 0) {
                inputs++;
            } else if (material.test(stack)) {
                materials++;
            } else {
                return false;
            }
        }
        return inputs == 1 && materials > 0 && materialCount.matches(materials);
    }

    @Override
    public ItemStack assemble(CraftingInput input) {
        ItemStack found = ItemStack.EMPTY;
        int materials = 0;
        for (ItemStack stack : input.items()) {
            if (stack.isEmpty()) {
                continue;
            }
            if (this.input.test(stack) && found.isEmpty()) {
                found = stack;
            } else if (material.test(stack)) {
                materials++;
            }
        }
        if (found.isEmpty()) {
            return ItemStack.EMPTY;
        }
        ItemStackTemplate made = result.resolve(found.typeHolder());
        return createWithOriginalComponents(made, found,
                made.count() + (addMaterialCountToResult ? materials : 0));
    }

    @Override
    public List<RecipeDisplay> display() {
        return List.of(new ShapelessCraftingRecipeDisplay(List.of(input.display(), material.display()),
                result.item().isPresent()
                        ? new SlotDisplay.ItemStackSlotDisplay(result.resolve(result.item().get()))
                        : input.display(),
                new SlotDisplay.ItemSlotDisplay(Items.CRAFTING_TABLE)));
    }
    // Generated by tools/kiln-stubs.py: what the mods use that isn't written by hand yet; names and signatures only.
    public static final net.minecraft.advancements.predicates.MinMaxBounds.Ints FULL_RANGE_MATERIAL_COUNT = new net.minecraft.advancements.predicates.MinMaxBounds.Ints((net.minecraft.advancements.predicates.MinMaxBounds.Bounds) null, (net.minecraft.advancements.predicates.MinMaxBounds.Bounds) null);
    // End of what tools/kiln-stubs.py generated.
}
