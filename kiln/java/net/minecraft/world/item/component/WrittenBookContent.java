package net.minecraft.world.item.component;

import com.mojang.serialization.Codec;
import com.mojang.serialization.codecs.RecordCodecBuilder;
import java.util.List;
import net.minecraft.network.chat.Component;
import net.minecraft.network.chat.ComponentSerialization;
import net.minecraft.server.network.Filterable;

/**
 * Kiln's stand-in for {@code WrittenBookContent}: a signed book's title, author, generation (0 the original, 1 a copy,
 * 2 a copy of a copy, 3 tattered) and pages ({@code minecraft:written_book_content}), read and written as the game
 * saves them.
 */
public record WrittenBookContent(Filterable<String> title, String author, int generation,
        List<Filterable<Component>> pages, boolean resolved) {
    public static final int TITLE_MAX_LENGTH = 32;
    public static final int MAX_GENERATION = 3;
    public static final WrittenBookContent EMPTY = new WrittenBookContent(Filterable.passThrough(""), "", 0, List.of(),
            true);
    public static final Codec<WrittenBookContent> CODEC = RecordCodecBuilder.create(i -> i.group(
            Filterable.codec(Codec.string(0, TITLE_MAX_LENGTH)).fieldOf("title").forGetter(WrittenBookContent::title),
            Codec.STRING.fieldOf("author").forGetter(WrittenBookContent::author),
            Codec.intRange(0, MAX_GENERATION).optionalFieldOf("generation", 0).forGetter(WrittenBookContent::generation),
            Filterable.codec(ComponentSerialization.CODEC).listOf().optionalFieldOf("pages", List.of())
                    .forGetter(WrittenBookContent::pages),
            Codec.BOOL.optionalFieldOf("resolved", false).forGetter(WrittenBookContent::resolved))
            .apply(i, WrittenBookContent::new));

    public WrittenBookContent {
        pages = List.copyOf(pages);
    }

    /** The pages as shown, the filtered ones when filtering is on. */
    public List<Component> getPages(boolean filterEnabled) {
        return pages.stream().map(page -> page.get(filterEnabled)).toList();
    }

    /** A copy one generation on; null for a copy of a copy, which can't be copied. */
    public WrittenBookContent tryCraftCopy() {
        return generation >= 2 ? null : new WrittenBookContent(title, author, generation + 1, pages, resolved);
    }

    public WrittenBookContent markResolved() {
        return new WrittenBookContent(title, author, generation, pages, true);
    }
    // Generated by tools/kiln-stubs.py: what the mods use that isn't written by hand yet; names and signatures only.
    public net.minecraft.world.item.component.WrittenBookContent craftCopy() { kiln.Missing.called("net.minecraft.world.item.component.WrittenBookContent.craftCopy"); return this; }
    // End of what tools/kiln-stubs.py generated.
}
