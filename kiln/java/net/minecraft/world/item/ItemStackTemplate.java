package net.minecraft.world.item;

import com.mojang.serialization.Codec;
import com.mojang.serialization.codecs.RecordCodecBuilder;
import net.minecraft.core.Holder;
import net.minecraft.core.component.DataComponentPatch;

/**
 * Kiln's stand-in for {@code ItemStackTemplate}: what a recipe makes, or an item leaves behind (a bucket). Kiln's
 * templates carry no components yet: {@link #create} makes the item and the count.
 */
public record ItemStackTemplate(Holder<Item> item, int count, DataComponentPatch components) {
    /** As a data pack writes one ({@code {"id": "minecraft:raw_iron", "count": 2}}); its components are left out. */
    public static final Codec<ItemStackTemplate> CODEC = RecordCodecBuilder.create(i -> i.group(
            Codec.STRING.comapFlatMap(id -> kiln.Recipes.item(id).map(Holder::direct),
                    (Holder<Item> item) -> item.value().kiln$id().toString()).fieldOf("id").forGetter(ItemStackTemplate::item),
            Codec.INT.optionalFieldOf("count", 1).forGetter(ItemStackTemplate::count))
            .apply(i, (item, count) -> new ItemStackTemplate(item, count, DataComponentPatch.EMPTY)));

    public ItemStackTemplate(Item item) {
        this(Holder.direct(item), 1, DataComponentPatch.EMPTY);
    }

    public ItemStackTemplate(Item item, int count) {
        this(Holder.direct(item), count, DataComponentPatch.EMPTY);
    }

    public ItemStackTemplate(Item item, DataComponentPatch components) {
        this(Holder.direct(item), 1, components);
    }

    public static ItemStackTemplate fromNonEmptyStack(ItemStack stack) {
        return new ItemStackTemplate(stack.getItem(), stack.getCount());
    }

    public static ItemStackTemplate fromNonEmptyStack(ItemStack stack, int count) {
        return new ItemStackTemplate(stack.getItem(), count);
    }

    public ItemStackTemplate withCount(int count) {
        return new ItemStackTemplate(item, count, components);
    }

    public Holder<Item> typeHolder() {
        return item;
    }

    public ItemStack create() {
        return new ItemStack(item.value(), count);
    }
    // Generated by tools/kiln-stubs.py: what the mods use that isn't written by hand yet; names and signatures only.
    public static final net.minecraft.network.codec.StreamCodec<net.minecraft.network.RegistryFriendlyByteBuf, net.minecraft.world.item.ItemStackTemplate> STREAM_CODEC = kiln.Constants.streamCodec("net.minecraft.world.item.ItemStackTemplate.STREAM_CODEC");
    // End of what tools/kiln-stubs.py generated.
}
