    public static VoxelShape box(double x1, double y1, double z1, double x2, double y2, double z2) {
        if (x2 - x1 < 1.0E-7 || y2 - y1 < 1.0E-7 || z2 - z1 < 1.0E-7) {
            return empty();
        }
        return kiln.BoxShape.of(List.of(new AABB(x1, y1, z1, x2, y2, z2)));
    }

    public static VoxelShape create(double x1, double y1, double z1, double x2, double y2, double z2) {
        return box(x1, y1, z1, x2, y2, z2);
    }

    public static VoxelShape create(AABB box) {
        return box(box.minX, box.minY, box.minZ, box.maxX, box.maxY, box.maxZ);
    }

    public static VoxelShape or(VoxelShape first, VoxelShape second) {
        List<AABB> all = new ArrayList<>(first.toAabbs());
        all.addAll(second.toAabbs());
        return kiln.BoxShape.of(all);
    }

    public static VoxelShape or(VoxelShape first, VoxelShape... more) {
        VoxelShape joined = first;
        for (VoxelShape shape : more) {
            joined = or(joined, shape);
        }
        return joined;
    }

