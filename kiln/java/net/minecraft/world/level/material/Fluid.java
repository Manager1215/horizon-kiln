package net.minecraft.world.level.material;

import net.minecraft.world.item.Item;
import net.minecraft.world.item.Items;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.state.BlockState;

/**
 * Kiln's stand-in for {@code Fluid}: a kind of liquid. The game's (water, lava) are in {@link Fluids}; a mod's fluids
 * are its own subclasses, registered in {@code BuiltInRegistries.FLUID}. Horizon has the liquids in the world: a Kiln
 * fluid is what a mod's tank or recipe holds, and the bucket that carries it.
 */
public abstract class Fluid {
    private FluidState defaultState;

    protected Fluid() {}

    /** Its state as a source block, or as the flowing liquid for a flowing fluid. */
    public FluidState defaultFluidState() {
        if (defaultState == null) {
            defaultState = new FluidState(this);
        }
        return defaultState;
    }

    /** The bucket that holds a block of it: none (air) for a fluid without one. */
    public Item getBucket() {
        return Items.AIR;
    }

    public boolean isSame(Fluid fluid) {
        return fluid == this;
    }

    /**
     * Whether it is in {@code tag}: the game's {@code minecraft:water} and {@code minecraft:lava} hold the source and the
     * flowing liquid. Kiln knows no other fluid tag yet (a mod's fluid in the water tag, say): none holds it.
     */
    public boolean is(net.minecraft.tags.TagKey<Fluid> tag) {
        if (tag == null || tag.location() == null) {
            return false;
        }
        String id = tag.location().toString();
        return switch (id) {
            case "minecraft:water" -> this == Fluids.WATER || this == Fluids.FLOWING_WATER;
            case "minecraft:lava" -> this == Fluids.LAVA || this == Fluids.FLOWING_LAVA;
            default -> false;
        };
    }

    public boolean isSource(FluidState state) {
        return false;
    }

    /** How much of a block it fills, out of 8. */
    public int getAmount(FluidState state) {
        return 0;
    }

    protected boolean isEmpty() {
        return false;
    }

    protected BlockState createLegacyBlock(FluidState state) {
        return Blocks.AIR.defaultBlockState();
    }
    // Generated by tools/kiln-stubs.py: what the mods use that isn't written by hand yet; names and signatures only.
    public int getTickDelay(net.minecraft.world.level.LevelReader p0) { kiln.Missing.called("net.minecraft.world.level.material.Fluid.getTickDelay"); return 0; }
    public java.util.Optional<net.minecraft.sounds.SoundEvent> getPickupSound() { kiln.Missing.called("net.minecraft.world.level.material.Fluid.getPickupSound"); return null; }
    public net.minecraft.core.Holder.Reference<net.minecraft.world.level.material.Fluid> builtInRegistryHolder() { kiln.Missing.called("net.minecraft.world.level.material.Fluid.builtInRegistryHolder"); return null; }
    // End of what tools/kiln-stubs.py generated.
}
