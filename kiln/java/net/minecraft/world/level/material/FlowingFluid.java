package net.minecraft.world.level.material;

/**
 * Kiln's stand-in for {@code FlowingFluid}: a fluid that spreads, as a source and as its flowing form. Horizon spreads
 * the game's in the world; for a mod's, this is what its tanks and buckets hold.
 */
public abstract class FlowingFluid extends Fluid {
    public FlowingFluid() {}

    public abstract Fluid getFlowing();

    public abstract Fluid getSource();

    public FluidState getFlowing(int amount, boolean falling) {
        return getFlowing().defaultFluidState();
    }

    public FluidState getSource(boolean falling) {
        return getSource().defaultFluidState();
    }
    // Generated by tools/kiln-stubs.py: what the mods use that isn't written by hand yet; names and signatures only.
    // End of what tools/kiln-stubs.py generated.
}
