    /** Kiln's own: the blocks above are registered (this class loaded) before Kiln looks one up by id. */
    static void kiln$load() {}

    /** The game's block {@code name}, as its own class where Kiln has it (by the game's data, else plain). */
    private static Block register(String name) {
        Identifier id = Identifier.withDefaultNamespace(name);
        return register(name, p -> kiln.GameBlocks.make(id, p));
    }

    /** The game's block {@code name}: the one the registry holds, else made by the game's data. */
    private static Block game(String name) {
        return Block.kiln$byId("minecraft:" + name);
    }

    private static Block register(String name, java.util.function.Function<BlockBehaviour.Properties, Block> make) {
        Identifier id = Identifier.withDefaultNamespace(name);
        return Registry.register(BuiltInRegistries.BLOCK, id,
                make.apply(BlockBehaviour.Properties.of().setId(ResourceKey.create(Registries.BLOCK, id))));
    }

