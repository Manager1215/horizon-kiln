package net.minecraft.world.level.block;

import java.util.Map;
import net.minecraft.core.BlockPos;
import net.minecraft.core.Direction;
import net.minecraft.world.item.context.BlockPlaceContext;
import net.minecraft.world.level.block.state.BlockBehaviour;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.block.state.StateDefinition;
import net.minecraft.world.level.block.state.properties.BlockStateProperties;
import net.minecraft.world.level.block.state.properties.BooleanProperty;
import net.minecraft.world.level.block.state.properties.EnumProperty;
import net.minecraft.world.level.block.state.properties.WallSide;

/**
 * Kiln's stand-in for {@code WallBlock}: a wall's post and its four sides, low where a wall, fence gate or bars stand
 * beside it (D-226). The game's own full blocks and the tall sides (a block above) aren't told here.
 */
public class WallBlock extends Block implements SimpleWaterloggedBlock {
    public static final BooleanProperty UP = BlockStateProperties.UP;
    public static final EnumProperty<WallSide> EAST = BlockStateProperties.EAST_WALL;
    public static final EnumProperty<WallSide> NORTH = BlockStateProperties.NORTH_WALL;
    public static final EnumProperty<WallSide> SOUTH = BlockStateProperties.SOUTH_WALL;
    public static final EnumProperty<WallSide> WEST = BlockStateProperties.WEST_WALL;
    public static final Map<Direction, EnumProperty<WallSide>> PROPERTY_BY_DIRECTION = Map.of(Direction.NORTH, NORTH,
            Direction.EAST, EAST, Direction.SOUTH, SOUTH, Direction.WEST, WEST);
    public static final BooleanProperty WATERLOGGED = BlockStateProperties.WATERLOGGED;
    public java.util.function.Function<BlockState, net.minecraft.world.phys.shapes.VoxelShape> shapes;
    public java.util.function.Function<BlockState, net.minecraft.world.phys.shapes.VoxelShape> collisionShapes;

    public WallBlock(BlockBehaviour.Properties properties) {
        super(properties);
        registerDefaultState(stateDefinition.any().setValue(UP, true).setValue(NORTH, WallSide.NONE)
                .setValue(EAST, WallSide.NONE).setValue(SOUTH, WallSide.NONE).setValue(WEST, WallSide.NONE)
                .setValue(WATERLOGGED, false));
    }

    protected WallBlock() {
        this(null);
    }

    private static boolean joins(BlockState neighbor, Direction side) {
        Block block = neighbor.getBlock();
        return block instanceof WallBlock || block instanceof IronBarsBlock
                || block instanceof FenceGateBlock && FenceGateBlock.connectsToDirection(neighbor, side);
    }

    private BlockState joined(BlockState state, net.minecraft.world.level.BlockGetter level, BlockPos pos) {
        for (Direction side : Direction.Plane.HORIZONTAL) {
            state = state.setValue(PROPERTY_BY_DIRECTION.get(side),
                    joins(level.getBlockState(pos.relative(side)), side.getOpposite()) ? WallSide.LOW : WallSide.NONE);
        }
        return state;
    }

    @Override
    public BlockState getStateForPlacement(BlockPlaceContext context) {
        return joined(defaultBlockState(), context.getLevel(), context.getClickedPos());
    }

    @Override
    protected BlockState updateShape(BlockState state, net.minecraft.world.level.LevelReader level,
            net.minecraft.world.level.ScheduledTickAccess ticks, BlockPos pos, Direction direction, BlockPos neighborPos,
            BlockState neighbor, net.minecraft.util.RandomSource random) {
        EnumProperty<WallSide> side = PROPERTY_BY_DIRECTION.get(direction);
        return side == null ? state
                : state.setValue(side, joins(neighbor, direction.getOpposite()) ? WallSide.LOW : WallSide.NONE);
    }

    /** A neighbour changed: the sides join again as the neighbours are now (Kiln doesn't call updateShape). */
    @Override
    protected void neighborChanged(BlockState state, net.minecraft.world.level.Level level, BlockPos pos,
            Block neighborBlock, net.minecraft.world.level.redstone.Orientation orientation, boolean movedByPiston) {
        BlockState joined = joined(state, level, pos);
        if (joined != state) {
            level.setBlock(pos, joined, UPDATE_CLIENTS);
        }
    }

    @Override
    protected void createBlockStateDefinition(StateDefinition.Builder<Block, BlockState> builder) {
        builder.add(UP, NORTH, EAST, WEST, SOUTH, WATERLOGGED);
    }
    // Generated by tools/kiln-stubs.py: what the mods use that isn't written by hand yet; names and signatures only.
    protected net.minecraft.world.phys.shapes.VoxelShape getCollisionShape(net.minecraft.world.level.block.state.BlockState p0, net.minecraft.world.level.BlockGetter p1, net.minecraft.core.BlockPos p2, net.minecraft.world.phys.shapes.CollisionContext p3) { kiln.Missing.called("net.minecraft.world.level.block.WallBlock.getCollisionShape"); return null; }
    // End of what tools/kiln-stubs.py generated.
}
