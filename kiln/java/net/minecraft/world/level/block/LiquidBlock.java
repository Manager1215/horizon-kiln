package net.minecraft.world.level.block;

import java.util.Optional;
import net.minecraft.core.BlockPos;
import net.minecraft.sounds.SoundEvent;
import net.minecraft.world.entity.LivingEntity;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.level.LevelAccessor;
import net.minecraft.world.level.block.state.BlockBehaviour;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.material.FlowingFluid;

/**
 * Kiln's stand-in for {@code LiquidBlock}: the game's water and lava (and a mod's liquid) as blocks. Horizon has them
 * in the world and makes them flow; a mod's code finds what they hold ({@code getFluidState}) and takes up a source
 * ({@code pickupBlock}), as a bucket or a sponge does.
 */
public class LiquidBlock extends Block implements BucketPickup {
    public FlowingFluid fluid;

    public LiquidBlock(FlowingFluid fluid, BlockBehaviour.Properties properties) {
        super(properties);
        this.fluid = fluid;
    }

    /** A source (level 0) becomes air, and its bucket full of it is given back; a flowing liquid gives nothing. */
    @Override
    public ItemStack pickupBlock(LivingEntity entity, LevelAccessor level, BlockPos pos, BlockState state) {
        if (!state.kiln$values().getOrDefault("level", "0").equals("0")) {
            return ItemStack.EMPTY;
        }
        if (!(level instanceof net.minecraft.world.level.Level writable)
                || !writable.setBlock(pos, Blocks.AIR.defaultBlockState(), Block.UPDATE_ALL_IMMEDIATE)) {
            return ItemStack.EMPTY;
        }
        return new ItemStack(fluid.getBucket());
    }

    @Override
    public Optional<SoundEvent> getPickupSound() {
        return Optional.empty();
    }
    // Generated by tools/kiln-stubs.py: what the mods use that isn't written by hand yet; names and signatures only.
    public static final net.minecraft.world.level.block.state.properties.IntegerProperty LEVEL = net.minecraft.world.level.block.state.properties.BlockStateProperties.LEVEL;
    // End of what tools/kiln-stubs.py generated.
}
