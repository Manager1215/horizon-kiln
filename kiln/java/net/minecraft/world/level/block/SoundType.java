package net.minecraft.world.level.block;

import net.minecraft.resources.Identifier;
import net.minecraft.sounds.SoundEvent;

/**
 * Kiln's stand-in for {@code SoundType}: a block's sounds, by the game's ids. Horizon plays a mod block's from its
 * content mod's template; Kiln keeps what a mod gives, and a mod's code that plays one of the game's (a crop's planting
 * sound) has its id.
 */
public class SoundType {
    public static final SoundType WOOD = of(1.0F, 1.0F, "block.wood.break", "block.wood.step", "block.wood.place",
            "block.wood.hit", "block.wood.fall");
    public static final SoundType GRASS = of(1.0F, 1.0F, "block.grass.break", "block.grass.step", "block.grass.place",
            "block.grass.hit", "block.grass.fall");
    public static final SoundType STONE = of(1.0F, 1.0F, "block.stone.break", "block.stone.step", "block.stone.place",
            "block.stone.hit", "block.stone.fall");
    public static final SoundType METAL = of(1.0F, 1.5F, "block.metal.break", "block.metal.step", "block.metal.place",
            "block.metal.hit", "block.metal.fall");
    public static final SoundType GLASS = of(1.0F, 1.0F, "block.glass.break", "block.stone.step", "block.glass.place",
            "block.stone.hit", "block.stone.fall");
    public static final SoundType CROP = of(1.0F, 1.0F, "block.crop.break", "block.grass.step", "item.crop.plant",
            "block.grass.hit", "block.grass.fall");
    public static final SoundType NETHER_WART = of(1.0F, 1.0F, "block.nether_wart.break", "block.stone.step",
            "item.nether_wart.plant", "block.stone.hit", "block.stone.fall");
    public static final SoundType ANVIL = of(0.3F, 1.0F, "block.anvil.break", "block.anvil.step", "block.anvil.place",
            "block.anvil.hit", "block.anvil.fall");
    private final float volume;
    private final float pitch;
    private final SoundEvent breakSound;
    private final SoundEvent stepSound;
    private final SoundEvent placeSound;
    private final SoundEvent hitSound;
    private final SoundEvent fallSound;

    public SoundType(float volume, float pitch, SoundEvent breakSound, SoundEvent stepSound, SoundEvent placeSound,
            SoundEvent hitSound, SoundEvent fallSound) {
        this.volume = volume;
        this.pitch = pitch;
        this.breakSound = breakSound;
        this.stepSound = stepSound;
        this.placeSound = placeSound;
        this.hitSound = hitSound;
        this.fallSound = fallSound;
    }

    private static SoundType of(float volume, float pitch, String breakSound, String stepSound, String placeSound,
            String hitSound, String fallSound) {
        return new SoundType(volume, pitch, sound(breakSound), sound(stepSound), sound(placeSound), sound(hitSound),
                sound(fallSound));
    }

    private static SoundEvent sound(String id) {
        return SoundEvent.createVariableRangeEvent(Identifier.withDefaultNamespace(id));
    }

    public float getVolume() {
        return volume;
    }

    public float getPitch() {
        return pitch;
    }

    public SoundEvent getBreakSound() {
        return breakSound;
    }

    public SoundEvent getStepSound() {
        return stepSound;
    }

    public SoundEvent getPlaceSound() {
        return placeSound;
    }

    public SoundEvent getHitSound() {
        return hitSound;
    }

    public SoundEvent getFallSound() {
        return fallSound;
    }
    // Generated by tools/kiln-stubs.py: what the mods use that isn't written by hand yet; names and signatures only.
    public static final net.minecraft.world.level.block.SoundType DEEPSLATE = null;
    // End of what tools/kiln-stubs.py generated.
}
