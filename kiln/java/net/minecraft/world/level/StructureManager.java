    public List<StructureStart> startsForStructure(int chunkX, int chunkZ, Predicate<Structure> matcher) {
        if (!Server.inCall()) {
            return List.of();
        }
        String answer = Server.ask("structures", level.dimension().identifier().toString(), Integer.toString(chunkX),
                Integer.toString(chunkZ));
        List<StructureStart> starts = new ArrayList<>();
        for (String entry : answer.isEmpty() ? new String[0] : answer.split(",")) {
            String[] f = entry.split(" ");
            if (f.length != 9) {
                continue;
            }
            try {
                Structure structure = Structure.kiln$of(f[0]);
                if (!matcher.test(structure)) {
                    continue;
                }
                int[] n = new int[8];
                for (int i = 0; i < 8; i++) {
                    n[i] = Integer.parseInt(f[i + 1]);
                }
                starts.add(StructureStart.kiln$of(structure, new ChunkPos(n[0], n[1]),
                        new BoundingBox(n[2], n[3], n[4], n[5], n[6], n[7])));
            } catch (RuntimeException e) {
                // An id or a number the game said wrong: that start is left out.
            }
        }
        return List.copyOf(starts);
    }
