package net.minecraft.world.entity;

import net.minecraft.world.entity.player.Player;
import net.minecraft.world.level.Level;

/**
 * Kiln's stand-in for {@code ExperienceOrb}: its value and how many orbs it holds, where it lies. Horizon keeps the orbs
 * in a world and gives them to players; Kiln makes one for the game's method mods' mixins go into ({@link
 * #playerTouch}, at Horizon's {@code experience_orb_pickup}, D-200).
 */
public class ExperienceOrb extends Entity {
    private int value;
    private int count = 1;

    public ExperienceOrb(Level level, double x, double y, double z, int value) {
        super();
        this.level = level;
        this.x = x;
        this.y = y;
        this.z = z;
        this.value = value;
    }

    public ExperienceOrb(Level level, net.minecraft.world.phys.Vec3 pos, net.minecraft.world.phys.Vec3 motion, int value) {
        this(level, pos.x, pos.y, pos.z, value);
    }

    public ExperienceOrb(EntityType<? extends ExperienceOrb> type, Level level) {
        super();
        this.level = level;
    }

    protected ExperienceOrb() {
        super();
    }

    /** Kiln's own: the orb as Horizon's hook tells it. */
    public ExperienceOrb kiln$orb(int value, int count) {
        this.value = value;
        this.count = Math.max(1, count);
        return this;
    }

    public int getValue() {
        return value;
    }

    /** The orbs merged into this one: Horizon's count. */
    public int kiln$count() {
        return count;
    }

    /** The largest orb size not above {@code value}, as vanilla splits experience into orbs. */
    public static int getExperienceValue(int value) {
        int[] sizes = {2477, 1237, 617, 307, 149, 73, 37, 17, 7, 3};
        for (int size : sizes) {
            if (value >= size) {
                return size;
            }
        }
        return 1;
    }

    /**
     * A player touching it: Horizon gives them the experience, so the body is the bridge's ({@code
     * experience_orb_pickup}, D-200); a mixin that cancels it at its head leaves the orb. When a mod calls it, nothing
     * is given.
     */
    public void playerTouch(Player player) {
        if (kiln.Bridge.calling("playerTouch")) {
            kiln.Bridge.body(null, player);
            // Vanilla's call as the orb is taken, where mixins inject (pickup-notifications at take). It does nothing;
            // Horizon gave the experience (D-213).
            player.take(this, 1);
        }
    }
    // Generated by tools/kiln-stubs.py: what the mods use that isn't written by hand yet; names and signatures only.
    private int age;
    public static void award(net.minecraft.server.level.ServerLevel p0, net.minecraft.world.phys.Vec3 p1, int p2) { kiln.Missing.called("net.minecraft.world.entity.ExperienceOrb.award"); }
    // End of what tools/kiln-stubs.py generated.
}
