package net.minecraft.world.damagesource;

/**
 * Kiln's stand-in for {@code CombatTracker}: what hurt an entity lately, for its death message. Horizon's server
 * tracks the fights; a client's tracker, as the game's on the client, has no entries, so its death message is the
 * generic one, "Name died" (DeathLogPlus records it, D-218).
 */
public class CombatTracker {
    private final net.minecraft.world.entity.LivingEntity mob;

    public CombatTracker(net.minecraft.world.entity.LivingEntity mob) {
        this.mob = mob;
    }

    protected CombatTracker() {
        this(null);
    }

    /** The game's, with no entries: "Name died". */
    public net.minecraft.network.chat.Component getDeathMessage() {
        return net.minecraft.network.chat.Component.translatable("death.attack.generic",
                mob == null ? net.minecraft.network.chat.Component.empty() : mob.getDisplayName());
    }

    // Generated by tools/kiln-stubs.py: what the mods use that isn't written by hand yet; names and signatures only.
    public void recordDamage(net.minecraft.world.damagesource.DamageSource p0, float p1) { kiln.Missing.called("net.minecraft.world.damagesource.CombatTracker.recordDamage"); }
    // End of what tools/kiln-stubs.py generated.
}
