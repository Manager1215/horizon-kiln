package net.minecraft.world.inventory;

import net.minecraft.world.Container;
import net.minecraft.world.entity.player.Player;
import net.minecraft.world.item.ItemStack;

/**
 * Kiln's stand-in for {@code ItemCombinerMenu}, the menu of a station that makes one result of its inputs (an anvil's):
 * its fields are the game's, so the mods' mixins that shadow them apply ({@code inputSlots}, {@code resultSlots},
 * {@code player}; D-202). The game runs the real station; Kiln makes one for a recipe viewer and for the mixins in
 * its result (Kiln's Mixin bridge).
 */
public abstract class ItemCombinerMenu extends AbstractContainerMenu {
    protected final ResultContainer resultSlots = new ResultContainer();
    protected final Container inputSlots;
    /** The player at the station; null for a menu a recipe viewer made with no player at hand. */
    protected final Player player;

    /** Kiln's own: a station's menu of {@code menuType} over {@code inputSlots}, for {@code player} (or null). */
    protected ItemCombinerMenu(MenuType<?> menuType, int containerId, Container inputSlots, Player player) {
        super(menuType, containerId);
        this.inputSlots = inputSlots;
        this.player = player;
    }

    /** The game's: works the result out of the inputs. */
    public abstract void createResult();

    /** The game's {@code getResultSlot}: the result's slot, after the inputs. */
    public int getResultSlot() {
        return inputSlots.getContainerSize();
    }

    /** Whether the result can be taken. */
    protected boolean mayPickup(Player player, boolean hasStack) {
        return true;
    }

    /** The result taken: the game's station does the rest (Horizon's). */
    protected void onTake(Player player, ItemStack stack) {}

    @Override
    public void slotsChanged(Container container) {
        super.slotsChanged(container);
        if (container == inputSlots) {
            createResult();
        }
    }

    @Override
    public ItemStack quickMoveStack(Player player, int index) {
        return ItemStack.EMPTY;
    }

    @Override
    public boolean stillValid(Player player) {
        return true;
    }
    // Generated by tools/kiln-stubs.py: what the mods use that isn't written by hand yet; names and signatures only.
    public net.minecraft.world.inventory.ContainerLevelAccess access;
    public int resultSlotIndex;
    // End of what tools/kiln-stubs.py generated.
}
