    /** A comparator's signal from a container: none when it is empty, else 1 and up to 14 more as it fills. */
    public static int getRedstoneSignalFromContainer(Container container) {
        if (container == null || container.getContainerSize() == 0) {
            return 0;
        }
        float full = 0;
        boolean any = false;
        for (int i = 0; i < container.getContainerSize(); i++) {
            ItemStack stack = container.getItem(i);
            if (!stack.isEmpty()) {
                any = true;
                full += (float) stack.getCount() / container.getMaxStackSize(stack);
            }
        }
        return any ? 1 + (int) (full / container.getContainerSize() * 14) : 0;
    }

    /**
     * Moves {@code stack} into the slots from {@code start} to {@code end} (excluded), backwards if asked: first onto
     * stacks of the same item, then into empty slots that take it. Whether any of it moved.
     */
    protected boolean moveItemStackTo(ItemStack stack, int start, int end, boolean backwards) {
        boolean moved = false;
        for (int pass = 0; pass < 2 && !stack.isEmpty(); pass++) {
            for (int k = 0; k < end - start && !stack.isEmpty(); k++) {
                Slot slot = slots.get(backwards ? end - 1 - k : start + k);
                ItemStack there = slot.getItem();
                int max = slot.getMaxStackSize(stack);
                if (pass == 0 && !there.isEmpty() && ItemStack.isSameItemSameComponents(stack, there)
                        && there.getCount() < max) {
                    int n = Math.min(stack.getCount(), max - there.getCount());
                    there.grow(n);
                    stack.shrink(n);
                    slot.setChanged();
                    moved = true;
                } else if (pass == 1 && there.isEmpty() && slot.mayPlace(stack)) {
                    slot.setByPlayer(stack.split(Math.min(stack.getCount(), max)));
                    moved = true;
                }
            }
        }
        return moved;
    }
